# Whitelist: whitelist.ips (IP/CIDR per line) and whitelist.ports (port spec per line)
wl_ips_load() { # dir -> canonical "fam cidr" lines on stdout
    local f="$1/whitelist.ips"
    [[ -f $f ]] || return 0
    cidr_canon any 1 0 0 <"$f" || die "$f: invalid entry (see message above)"
}
wl_ports_load() { # dir -> normalized spec or empty
    local f="$1/whitelist.ports" all=""
    [[ -f $f ]] || return 0
    all=$(sed 's/#.*//' "$f" | tr -d ' \t\r' | grep -v '^$' | paste -sd, - || true)
    [[ -z $all ]] && return 0
    parse_ports "$all" || die "$f: invalid port entry"
}

# custom.sources: "<id> url <https-url>" | "<id> asn <number>" | "<id> file -"
custom_lookup() { # dir id -> prints "type value"
    local f="$1/custom.sources" id=$2 a b c
    [[ -f $f ]] || return 1
    while read -r a b c; do
        [[ $a == "$id" ]] && { echo "$b ${c:-}"; return 0; }
    done <"$f"
    return 1
}

