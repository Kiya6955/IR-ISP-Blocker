# ------------------------------------------------------------------ interactive menu
pause() { [[ -t 0 ]] && read -r -p "$(t press_enter)" _ || true; }

ask() { # prompt validator-fn default -> echoes value
    local prompt=$1 fn=$2 def=${3:-} v
    while true; do
        read -r -p "$prompt" v || exit 0
        v=${v:-$def}
        if "$fn" "$v"; then echo "$v"; return 0; fi
        { t invalid; echo; } >&2
    done
}
v_ports()  { parse_ports "$1" >/dev/null 2>&1; }
v_ports_only() { [[ $1 != all ]] && parse_ports "$1" >/dev/null 2>&1; }
v_123()    { [[ $1 =~ ^[123]$ ]]; }
v_1234()   { [[ $1 =~ ^[1234]$ ]]; }
v_any()    { return 0; }
v_1to5()   { [[ $1 =~ ^[1-5]$ ]]; }
v_1to7()   { [[ $1 =~ ^[1-7]$ ]]; }
v_yesno()  { [[ $1 =~ ^(yes|no)$ ]]; }
v_backend() { [[ $1 =~ ^(auto|nft|ipset|iptables)$ ]]; }
v_docker() { [[ $1 =~ ^(auto|yes|no)$ ]]; }
v_dur()    { [[ -z $1 ]] || parse_duration "$1" >/dev/null; }
v_rate()   { [[ $1 =~ ^[0-9]+/(second|minute|hour|day)$ ]]; }
v_asns()   { [[ ${1^^} =~ ^(AS)?[0-9]+(,(AS)?[0-9]+)*$ ]]; }
v_url()    { [[ $1 == https://* ]]; }
v_name()   { [[ $1 =~ ^[A-Za-z0-9_-]{1,20}$ ]]; }
v_file()   { [[ -r $1 ]]; }
v_ports_opt() { [[ -z $1 ]] || parse_ports "$1" >/dev/null 2>&1; }
v_ipsopt() {
    [[ -z $1 ]] && return 0
    local e items=()
    split_csv items "$1"
    for e in "${items[@]}"; do valid_ip_any "$e" || return 1; done
}
v_isps() {
    local e n=${#ISP_ORDER[@]} items=()
    split_csv items "$1"
    [[ ${#items[@]} -gt 0 ]] || return 1
    for e in "${items[@]}"; do
        [[ ${e,,} == c ]] && continue
        if [[ $e =~ ^[0-9]+$ ]]; then (( e >= 1 && e <= n )) || return 1
        else [[ -n ${ISP_EN[${e,,}]:-} ]] || return 1; fi
    done
}
isps_from_choice() {
    local e out=() items=()
    split_csv items "$1"
    for e in "${items[@]}"; do
        [[ ${e,,} == c ]] && continue
        if [[ $e =~ ^[0-9]+$ ]]; then out+=("${ISP_ORDER[$((e - 1))]}"); else out+=("${e,,}"); fi
    done
    (IFS=,; echo "${out[*]}")
}

show_isps() {
    local i=1 id cat=""
    for id in "${ISP_ORDER[@]}"; do
        if [[ ${ISP_CAT[$id]} != "$cat" ]]; then cat=${ISP_CAT[$id]}; printf '\n  %s%s%s\n' "$C_DIM" "${cat^^}" "$C_RST"; fi
        printf '  %s%3d%s  %-12s %s %s(%s v4 / %s v6)%s\n' "$C_BLU" "$i" "$C_RST" "$id" "$(isp_name "$id")" "$C_DIM" "${ISP_V4[$id]}" "${ISP_V6[$id]}" "$C_RST"
        i=$((i + 1))
    done
}

reset_opts() {
    OPT_ISPS=""; OPT_ASNS=""; OPT_URL=""; OPT_FILE=""; OPT_NAME=""; OPT_PORTS=""; OPT_PROTO=""; OPT_DIR=""
    OPT_ACTION=""; OPT_RATE=""; OPT_RAW=0; OPT_FOR=""; OPT_REPLACE=0; OPT_DEADMAN=""; OPT_RULE=""; OPT_ALL=0; POS=()
    OPT_WL=""; OPT_TO=""; OPT_LIST=0
}

menu_block() { # mode
    local mode=$1 c
    local raw
    show_isps
    printf '\n  %sc%s    custom source (ASN, list URL or local file)\n\n' "$C_BLU" "$C_RST"
    raw=$(ask "$(t pick_isps)" v_isps)
    OPT_ISPS=$(isps_from_choice "$raw")
    [[ ,${raw,,}, == *,c,* ]] && menu_custom_source
    if [[ $mode == only ]]; then OPT_PORTS=$(ask "$(t ask_only_ports)" v_ports_only)
    else OPT_PORTS=$(ask "$(t ask_ports)" v_ports all); fi
    if [[ $(parse_ports "$OPT_PORTS") != all ]]; then
        c=$(ask "$(t ask_proto)" v_123 1); case $c in 1) OPT_PROTO=both ;; 2) OPT_PROTO=tcp ;; 3) OPT_PROTO=udp ;; esac
    fi
    if [[ $mode == block ]]; then
        c=$(ask "$(t ask_dir)" v_123 1); case $c in 1) OPT_DIR=in ;; 2) OPT_DIR=out ;; 3) OPT_DIR=both ;; esac
    fi
    c=$(ask "$(t ask_action)" v_1234 1)
    case $c in 1) OPT_ACTION=drop ;; 2) OPT_ACTION=reject ;; 3) OPT_ACTION=log ;; 4) OPT_ACTION=ratelimit; OPT_RATE=$(ask "Allowed rate per source IP, e.g. 30/minute [30/minute]: " v_rate 30/minute) ;; esac
    OPT_FOR=$(ask "Time limit, e.g. 90m, 24h, 7d (empty = permanent): " v_dur "")
    if [[ $mode == block ]]; then
        read -r -p "Drop before connection tracking (advanced, --raw)? [y/N]: " c || true
        [[ $c =~ ^[Yy] ]] && OPT_RAW=1
    fi
    OPT_WL=$(ask "$(t ask_wl)" v_ipsopt "")
    if [[ -f $IRB_ETC/rules.conf ]] && grep -q '^id=' "$IRB_ETC/rules.conf"; then
        read -r -p "$(t ask_replace)" c || true; [[ $c =~ ^[Yy] ]] && OPT_REPLACE=1
    fi
    if [[ $OPT_PORTS == all || $mode == only ]]; then
        read -r -p "$(t ask_deadman 90)" c || true; [[ $c =~ ^[Nn] ]] || OPT_DEADMAN=90
    fi
    run_sub cmd_block_or_only "$mode"
}

