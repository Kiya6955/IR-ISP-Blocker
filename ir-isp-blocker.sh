UTF8=0
case ${LC_ALL:-${LC_CTYPE:-${LANG:-}}} in *[Uu][Tt][Ff]-8* | *[Uu][Tt][Ff]8*) UTF8=1 ;; esac
HDR_W=48

draw_header() {
    local tl='+' tr='+' bl='+' br='+' h='-' v='|' bar='' i
    if [[ $UTF8 -eq 1 ]]; then tl='╭'; tr='╮'; bl='╰'; br='╯'; h='─'; v='│'; fi
    for ((i = 0; i < HDR_W; i++)); do bar+="$h"; done
    printf '  %s%s%s%s%s\n' "$C_BLU" "$tl" "$bar" "$tr" "$C_RST"
    printf '  %s%s%s %s%-*s%s %s%s%s\n' "$C_BLU" "$v" "$C_RST" "$C_BLD" $((HDR_W - 2)) "$(t title "$IRB_VERSION")" "$C_RST" "$C_BLU" "$v" "$C_RST"
    printf '  %s%s%s %s%-*s%s %s%s%s\n' "$C_BLU" "$v" "$C_RST" "$C_DIM" $((HDR_W - 2)) "github.com/Kiya6955/IR-ISP-Blocker" "$C_RST" "$C_BLU" "$v" "$C_RST"
    printf '  %s%s%s%s%s\n' "$C_BLU" "$bl" "$bar" "$br" "$C_RST"
}

