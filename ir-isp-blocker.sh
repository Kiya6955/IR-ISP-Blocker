        local id idl=()
        split_csv idl "${R_ISPS[i]}"
        [[ ${R_MODE[i]} == only ]] && idl+=(others)
        for id in "${idl[@]}"; do
            [[ $id == others ]] && { say "      $(printf '%-12s' others) hits=${HITS[r${R_ID[i]}:others]:-0}"; continue; }
            say "      $(printf '%-12s' "$id") hits=${HITS[r${R_ID[i]}:$id]:-0}  $(isp_name "$id")"
        done
    done
    legacy_notice
}

cmd_doctor() {
    local issues=0
    chk_ok()   { printf '  %sOK%s    %s\n' "$C_GRN" "$C_RST" "$*"; }
    chk_warn() { printf '  %sWARN%s  %s\n' "$C_YEL" "$C_RST" "$*"; issues=$((issues + 1)); }
    chk_info() { printf '  %sINFO%s  %s\n' "$C_BLU" "$C_RST" "$*"; }
    cfg_load "$IRB_ETC"; rules_load "$IRB_ETC"; index_load || true
    say "${C_BLD}ir-isp-blocker doctor${C_RST}"
    if is_root; then chk_ok "running as root"; else chk_warn "not root: many checks are skipped/inaccurate"; fi
    local v; v=$(virt_kind); chk_info "virtualization: ${v:-none detected}"
    [[ $v == openvz || $v == lxc ]] && chk_warn "$v container: nftables/ipset may be unavailable; plain iptables fallback is used if needed"
    local b
    for b in nft ipset iptables; do
        if backend_usable "$b"; then chk_ok "backend '$b' usable"; else chk_info "backend '$b' not usable"; fi
    done
    if [[ -r /proc/modules ]]; then
        local mod
        for mod in nf_tables ip_set xt_set nf_conntrack; do
            if grep -q "^$mod " /proc/modules; then chk_ok "kernel module $mod loaded"; else chk_info "kernel module $mod not loaded (may be built-in or loaded on demand)"; fi
        done
    fi
    if have curl || have wget; then chk_ok "downloader present"; else chk_warn "neither curl nor wget installed"; fi
    local ssh; ssh=$(detect_ssh_ports)
    if [[ -n $ssh ]]; then chk_ok "SSH port(s): $ssh"; else chk_warn "no SSH port detected: blocking all ports would be refused"; fi
    if [[ $CFG_SSH_PROTECT == yes ]]; then chk_ok "SSH protection enabled"; else chk_warn "SSH protection DISABLED"; fi
    local c; c=$(detect_ssh_client); [[ -n $c ]] && chk_info "current SSH client: $c (auto-whitelisted on apply)"
    if [[ -n $LISTS_DATE ]]; then
        local age=$(( ( $(date +%s) - $(date -d "$LISTS_DATE" +%s 2>/dev/null || date +%s) ) / 86400 ))
        if (( age > 45 )); then chk_warn "IP lists are $age days old: run 'ir-isp-blocker update' (or update --auto weekly)"; else chk_ok "IP lists from $LISTS_DATE ($age days old)"; fi
    else
        chk_info "IP lists not downloaded yet"
    fi
    if [[ -x $IRB_BIN ]]; then chk_ok "installed at $IRB_BIN"; else chk_info "not installed (run: install)"; fi
    if has_systemd; then
        if systemctl is-enabled ir-isp-blocker.service >/dev/null 2>&1; then chk_ok "boot restore unit enabled"
        elif [[ ${#R_ID[@]} -gt 0 ]]; then chk_warn "boot restore unit not enabled (rules will vanish on reboot): run install"; fi
        systemctl is-active ufw >/dev/null 2>&1 && chk_info "ufw active: compatible (our chain is evaluated before ufw's; whitelist uses RETURN, never ACCEPT)"
        systemctl is-active firewalld >/dev/null 2>&1 && chk_info "firewalld active: compatible (separate nft table / chains)"
        if systemctl is-enabled nftables >/dev/null 2>&1 && grep -qs 'flush ruleset' /etc/nftables.conf /etc/sysconfig/nftables.conf; then
            chk_warn "nftables.service uses 'flush ruleset': 'systemctl reload nftables' wipes our table (boot is fine - we start after it). Run 'ir-isp-blocker apply' after reloading."
        fi
    fi
    local f
    for f in /etc/iptables/rules.v4 /etc/iptables/rules.v6 /etc/sysconfig/iptables; do
        [[ -r $f ]] || continue
        grep -q -- '--match-set irb[46]-' "$f" && chk_warn "$f references irb ipsets: iptables-persistent will fail at boot if it runs before us. Remove IRB-* lines from $f (we restore ourselves)."
        grep -q "$LEGACY_CHAIN" "$f" && chk_warn "$f contains the v1 '$LEGACY_CHAIN' chain: run 'ir-isp-blocker migrate'"
    done
    local n; n=$(legacy_rule_count); [[ ${n:-0} -gt 0 ]] && chk_warn "v1 '$LEGACY_CHAIN' chain is live ($n rules): run 'ir-isp-blocker migrate'"
    if have iptables && have nft && [[ $(iptables -V 2>/dev/null) == *legacy* && -n $(nft list tables 2>/dev/null) ]]; then
        chk_info "both iptables-legacy and nftables rules present: both are evaluated; a drop in either wins"
    fi
    detect_docker && chk_info "Docker detected: forward hook enabled (published ports matched on the original, pre-DNAT port)"
    if [[ $issues -eq 0 ]]; then ok "no problems found"; else warn "$issues warning(s)"; fi
    return 0
}

cmd_export() {
    local out=${POS[0]:-}
    local f
    {
        echo "# ir-isp-blocker export v2 ($(date -u +%FT%TZ))"
        for f in "${CONF_FILES[@]}"; do
            echo "[$f]"
            [[ -f $IRB_ETC/$f ]] && grep -v '^#' "$IRB_ETC/$f" || true
        done
    } >"${out:-/dev/stdout}"
    [[ -n $out ]] && ok "exported to $out"
    return 0
}

cmd_import() {
    local in=${POS[0]:-}
    [[ -n $in && -r $in ]] || die "usage: import FILE"
    begin_change
    mkwork
    local s="$WORK/stage" section="" line f
    rm -rf -- "$s"; mkdir -p -- "$s"
    while IFS= read -r line || [[ -n $line ]]; do
        line=${line%$'\r'}
        [[ $line == \#* || -z $line ]] && continue
        if [[ $line =~ ^\[([a-z.]+)\]$ ]]; then
            section=${BASH_REMATCH[1]}
            local okk=0
            for f in "${CONF_FILES[@]}"; do [[ $f == "$section" ]] && okk=1; done
            [[ $okk -eq 1 ]] || die "import: unknown section [$section]"
            : >"$s/$section"; continue
        fi
        [[ -n $section ]] || die "import: data before first section"
        printf '%s\n' "$line" >>"$s/$section"
    done <"$in"
    # validate everything strictly before applying
    cfg_load "$s"; rules_load "$s"; wl_ips_load "$s" >/dev/null; wl_ports_load "$s" >/dev/null
    if [[ -f $s/custom.sources ]]; then
        while read -r f line; do
            valid_id "$f" || die "import: bad custom id '$f'"
            [[ $line =~ ^(asn\ [1-9][0-9]*|url\ https://[^[:space:]]+|file\ -)$ ]] || die "import: bad custom source for $f"
        done <"$s/custom.sources"
    fi
    finish_change "$s" "import $in"
}

