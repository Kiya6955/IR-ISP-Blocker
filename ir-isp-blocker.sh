cleanup() {
    [[ -n $WORK && -d $WORK ]] && rm -rf -- "$WORK"
    if [[ $LOCK_HELD -eq 2 ]]; then rm -rf -- "$IRB_LOCK.d" 2>/dev/null || true; fi
}
on_err() {
    local rc=$? line=${1:-?}
    [[ $rc -eq 64 ]] && exit 1   # message already printed by die() in a subshell
    err "aborted (exit $rc, line $line); configuration was not committed."
    exit "$rc"
}

# run a command in a subshell WITH errexit active (a plain "( cmd ) || true" would silently
# disable set -e inside the subshell) and never abort the caller (interactive menu).
run_sub() {
    set +e
    # own temp dir + EXIT trap in the subshell (traps are not inherited by subshells)
    # shellcheck disable=SC2030,SC2031
    ( WORK=""; trap cleanup EXIT; set -e; "$@" )
    set -e
    return 0
}

release_lock() {
    case $LOCK_HELD in
        1) flock -u 9 2>/dev/null || true; exec 9>&- ;;
        2) rm -rf -- "$IRB_LOCK.d" 2>/dev/null || true ;;
    esac
    LOCK_HELD=0
}

# split_csv ARRAYNAME STRING : split on commas without word-splitting/globbing pitfalls
split_csv() {
    local -n _out=$1
    _out=()
    local _tmp=() _e
    IFS=, read -r -a _tmp <<<"$2"
    for _e in "${_tmp[@]}"; do _e=${_e//[[:space:]]/}; [[ -n $_e ]] && _out+=("$_e"); done
    return 0
}
