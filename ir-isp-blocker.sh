sync_timers() { # create/remove update + expire timers to match config
    [[ $DRY_RUN -eq 1 || $IRB_PERSIST == none ]] && return 0
    local need_expire=0 i
    for i in "${!R_ID[@]}"; do [[ ${R_EXP[i]} != 0 ]] && need_expire=1; done
    [[ -x $IRB_BIN ]] || return 0
    if has_systemd; then
        local reload=0
        if [[ $need_expire -eq 1 ]]; then
            write_unit ir-isp-blocker-expire.service "[Unit]
Description=IR-ISP-Blocker: remove expired time-limited rules
[Service]
Type=oneshot
ExecStart=$IRB_BIN expire" && reload=1
            write_unit ir-isp-blocker-expire.timer "[Unit]
Description=IR-ISP-Blocker: expire time-limited rules every 5 minutes
[Timer]
OnCalendar=*:0/5
Persistent=true
[Install]
WantedBy=timers.target" && reload=1
            [[ $reload -eq 1 ]] && systemctl daemon-reload
            systemctl enable --now ir-isp-blocker-expire.timer >/dev/null 2>&1 || true
        elif [[ -f $IRB_SYSTEMD_DIR/ir-isp-blocker-expire.timer ]]; then
            systemctl disable --now ir-isp-blocker-expire.timer >/dev/null 2>&1 || true
            rm -f -- "$IRB_SYSTEMD_DIR"/ir-isp-blocker-expire.{timer,service}
            systemctl daemon-reload
        fi
        reload=0
        if [[ $CFG_AUTO_UPDATE != off ]]; then
            write_unit ir-isp-blocker-update.service "[Unit]
Description=IR-ISP-Blocker: refresh IP lists and re-apply
Wants=network-online.target
After=network-online.target
[Service]
Type=oneshot
ExecStart=$IRB_BIN update --yes --quiet" && reload=1
            write_unit ir-isp-blocker-update.timer "[Unit]
Description=IR-ISP-Blocker: $CFG_AUTO_UPDATE list update
[Timer]
OnCalendar=$CFG_AUTO_UPDATE
RandomizedDelaySec=3h
Persistent=true
[Install]
WantedBy=timers.target" && reload=1
            [[ $reload -eq 1 ]] && systemctl daemon-reload
            systemctl enable --now ir-isp-blocker-update.timer >/dev/null 2>&1 || true
        elif [[ -f $IRB_SYSTEMD_DIR/ir-isp-blocker-update.timer ]]; then
            systemctl disable --now ir-isp-blocker-update.timer >/dev/null 2>&1 || true
            rm -f -- "$IRB_SYSTEMD_DIR"/ir-isp-blocker-update.{timer,service}
            systemctl daemon-reload
        fi
    elif [[ -d /etc/cron.d ]]; then
        local cron=""
        [[ $need_expire -eq 1 ]] && cron+="*/5 * * * * root $IRB_BIN expire >/dev/null 2>&1"$'\n'
        case $CFG_AUTO_UPDATE in
            daily)  cron+="17 4 * * * root $IRB_BIN update --yes --quiet >/dev/null 2>&1"$'\n' ;;
            weekly) cron+="17 4 * * 1 root $IRB_BIN update --yes --quiet >/dev/null 2>&1"$'\n' ;;
        esac
        if [[ -n $cron ]]; then printf '# managed by ir-isp-blocker\n%s' "$cron" >/etc/cron.d/ir-isp-blocker
        else rm -f /etc/cron.d/ir-isp-blocker; fi
    elif [[ $need_expire -eq 1 || $CFG_AUTO_UPDATE != off ]]; then
        warn "neither systemd nor /etc/cron.d found: expiry/auto-update are not scheduled (run 'ir-isp-blocker expire' / 'update' yourself)"
    fi
}

ensure_installed() { # quietly install/upgrade the binary + boot unit when state changes
    [[ $DRY_RUN -eq 1 ]] && return 0
    local cur=""
    [[ -x $IRB_BIN ]] && cur=$(sed -n 's/^IRB_VERSION="\(.*\)"$/\1/p' "$IRB_BIN" | head -1)
    if [[ $cur != "$IRB_VERSION" ]]; then
        local src
        src=$(self_source) || die "could not obtain a copy of the script to install"
        mkdir -p -- "$(dirname -- "$IRB_BIN")"
        { install -m 0755 "$src" "$IRB_BIN.tmp" && mv -f -- "$IRB_BIN.tmp" "$IRB_BIN"; } || die "cannot install $IRB_BIN"
        ok "$(t installed "$IRB_BIN")"
    fi
    install_persistence
}

cmd_install() {
    need_root; acquire_lock
    mkdir -p -- "$IRB_ETC" "$LISTS_DIR"
    if [[ $DRY_RUN -eq 1 ]]; then echo "+ install script to $IRB_BIN, boot unit, fetch catalogue"; return 0; fi
    local cur=""
    [[ -x $IRB_BIN ]] && cur=$(sed -n 's/^IRB_VERSION="\(.*\)"$/\1/p' "$IRB_BIN" | head -1)
    local src; src=$(self_source) || die "could not obtain a copy of the script"
    mkdir -p -- "$(dirname -- "$IRB_BIN")"
    { install -m 0755 "$src" "$IRB_BIN.tmp" && mv -f -- "$IRB_BIN.tmp" "$IRB_BIN"; } || die "cannot install $IRB_BIN"
    install_persistence
    [[ -f $IRB_ETC/config ]] || { cfg_defaults; cfg_save "$IRB_ETC"; }
    ok "$(t installed "$IRB_BIN") (previous: ${cur:-none})"
    lists_update || warn "$(t lists_kept)"
    legacy_notice
}

cmd_uninstall() {
    need_root; acquire_lock
    local keep=0
    [[ ${OPT_KEEP_CONFIG:-0} -eq 1 ]] && keep=1
    say "This removes all ir-isp-blocker firewall rules, timers, the boot unit and $IRB_BIN$([[ $keep -eq 1 ]] || echo " and $IRB_ETC")."
    confirm "$(t confirm_q)" || die "$(t aborted)"
    teardown_all
    [[ $DRY_RUN -eq 1 ]] && return 0
    if has_systemd && [[ $IRB_PERSIST != none ]]; then
        local u
        for u in ir-isp-blocker.service ir-isp-blocker-update.timer ir-isp-blocker-expire.timer; do
            systemctl disable --now "$u" >/dev/null 2>&1 || true
        done
        systemctl list-units --plain --no-legend 'irb-deadman-*' 2>/dev/null | awk '{print $1}' | while read -r u; do systemctl stop "$u" 2>/dev/null || true; done
        rm -f -- "$IRB_SYSTEMD_DIR"/ir-isp-blocker{.service,-update.service,-update.timer,-expire.service,-expire.timer}
        systemctl daemon-reload || true
    fi
    if [[ -f /etc/init.d/ir-isp-blocker ]]; then rc-update del ir-isp-blocker default >/dev/null 2>&1 || true; rm -f /etc/init.d/ir-isp-blocker; fi
    [[ -f /etc/rc.local ]] && sed -i '/# ir-isp-blocker$/d' /etc/rc.local
    rm -f /etc/cron.d/ir-isp-blocker
    rm -f -- "$IRB_BIN"
    [[ $keep -eq 1 ]] || rm -rf -- "${IRB_ETC:?}"
    ok "ir-isp-blocker removed."
}

# ------------------------------------------------------------------ dead-man switch
deadman_arm() { # seconds backup-id
    local secs=$1 bid=$2 unit
    [[ -x $IRB_BIN ]] || { warn "dead-man switch needs the installed binary"; return 1; }
    if has_systemd && have systemd-run; then
        unit="irb-deadman-$(date +%s)"
        systemd-run --quiet --unit="$unit" --on-active="${secs}s" --timer-property=AccuracySec=1s \
            "$IRB_BIN" rollback --to "$bid" --yes --quiet >/dev/null 2>&1 || return 1
        echo "systemd $unit" >"$IRB_ETC/state/deadman"
    else
        have setsid || { warn "setsid not found; dead-man switch unavailable"; return 1; }
        # shellcheck disable=SC2016  # positional args expand in the child sh
        setsid nohup sh -c 'sleep "$1"; exec "$2" rollback --to "$3" --yes --quiet' irb-deadman "$secs" "$IRB_BIN" "$bid" >/dev/null 2>&1 &
        echo "pid $!" >"$IRB_ETC/state/deadman"
    fi
    warn "Dead-man switch armed: rules roll back in ${secs}s unless confirmed ('ir-isp-blocker confirm')."
}
deadman_cancel() {
    local f="$IRB_ETC/state/deadman" kind val
    [[ -f $f ]] || return 1
    read -r kind val <"$f" || true
    case $kind in
        systemd) systemctl stop "$val.timer" "$val.service" >/dev/null 2>&1 || true ;;
        pid) [[ $val =~ ^[0-9]+$ ]] && kill -- "-$val" 2>/dev/null || kill "$val" 2>/dev/null || true ;;
    esac
    rm -f -- "$f"
    return 0
}
deadman_flow() { # seconds
    local secs=$1 a
    [[ -n $LAST_BACKUP ]] || return 0
    # the rollback job must be able to take the lock while we wait for the user
    release_lock
    deadman_arm "$secs" "$LAST_BACKUP" || return 0
    if [[ -t 0 ]]; then
        local wait=$(( secs > 15 ? secs - 5 : secs ))
        if read -r -t "$wait" -p "$(t confirm_keep "$secs")" a && [[ $a == yes || $a == y ]]; then
            deadman_cancel; ok "$(t kept)"
        else
            echo; warn "not confirmed - the dead-man switch will roll back (or run 'ir-isp-blocker confirm' now)"
        fi
    fi
}

# ------------------------------------------------------------------ legacy v1 migration
legacy_rule_count() {
    have iptables || { echo 0; return 0; }
    iptables -w -S "$LEGACY_CHAIN" 2>/dev/null | grep -c '^-A' || true
}
legacy_notice() {
    is_root || return 0
    local n; n=$(legacy_rule_count)
    [[ ${n:-0} -gt 0 ]] && warn "$(t legacy_found "$n")"
    return 0
}

# the migration must infer ISPs from the v1 chain itself, not from the command that triggered it
migrate_legacy_alone() { OPT_ISPS=""; cmd_migrate; }

# v2 replaces v1: when a v1 chain is still live, import it and remove it without asking
auto_migrate_legacy() {
    [[ $DRY_RUN -eq 1 ]] && return 0
    is_root || return 0
    [[ $(legacy_rule_count) -gt 0 ]] || return 0
    info "Old v1 rules found: importing them into v2 and removing the v1 chain."
    local saved=$ASSUME_YES
    ASSUME_YES=1
    run_sub migrate_legacy_alone
    ASSUME_YES=$saved
}

cmd_migrate() {
    need_root
    have iptables || die "iptables not installed: nothing to migrate"
    iptables -w -n -L "$LEGACY_CHAIN" >/dev/null 2>&1 || { ok "no v1 '$LEGACY_CHAIN' chain found - nothing to migrate"; return 0; }
    mkwork
    local dump="$WORK/legacy.txt" wl_ips ports wl_ports
    iptables -w -S "$LEGACY_CHAIN" >"$dump"
    local total; total=$(grep -c '^-A' "$dump" || true)
    # whitelisted IPs: "-A isp-blocker -s X -j ACCEPT" without port
    wl_ips=$(awk '$1=="-A" && /-j ACCEPT/ && !/--dport/ { for(i=1;i<=NF;i++) if($i=="-s") print $(i+1) }' "$dump" | sort -u | paste -sd, - || true)
    # ACCEPT on port without source (whitelisted ports / ssh)
    wl_ports=$(awk '$1=="-A" && /-j ACCEPT/ && /--dport/ && !/ -s / { for(i=1;i<=NF;i++) if($i=="--dport") print $(i+1) }' "$dump" | sort -un | paste -sd, - || true)
    ports=$(awk '$1=="-A" && /-j DROP/ { for(i=1;i<=NF;i++) if($i=="--dport") print $(i+1) }' "$dump" | sort -un | paste -sd, - || true)
    # v1 "<ISP> Only" mode: ISP sources ACCEPTed on ports, then DROP on those ports without a source
    local mode=block src_sel='/-j DROP/'
    if ! grep -q -- '-s .*-j DROP' "$dump" && grep -q -- '-s .*--dport .*-j ACCEPT' "$dump"; then
        mode=only; src_sel='/-j ACCEPT/ && /--dport/'
        wl_ports=$(awk '$1=="-A" && /-j ACCEPT/ && /--dport/ && !/ -s / { for(i=1;i<=NF;i++) if($i=="--dport") print $(i+1) }' "$dump" | sort -un | paste -sd, - || true)
    fi
    local proto=both nontcp nonudp
    nontcp=$(grep -- '-j DROP' "$dump" | grep -vc -- '-p tcp' || true)
    nonudp=$(grep -- '-j DROP' "$dump" | grep -vc -- '-p udp' || true)
    if grep -q -- '-j DROP' "$dump"; then
        if [[ $nontcp -eq 0 ]]; then proto=tcp; elif [[ $nonudp -eq 0 ]]; then proto=udp; fi
    fi
    say "v1 chain '$LEGACY_CHAIN': $total rules (mode: $mode)"
    say "  blocked ports found : ${ports:-all ports}"
    say "  whitelisted IPs     : ${wl_ips:-none}"
    say "  accepted ports      : ${wl_ports:-none}"
    # guess ISPs from the DROP sources using the cached/fetched v4 lists
    ensure_index
    local srcs="$WORK/legacy-src" guess=()
    awk '$1=="-A" && '"$src_sel"' { for(i=1;i<=NF;i++) if($i=="-s") print $(i+1) }' "$dump" | sort -u | head -400 >"$srcs" || true
    if [[ -s $srcs ]]; then
        local legacy_ids=(mci mtn tci rightel shatel asiatech pishgaman mobinnet parsonline) id hits
        ensure_lists "$IRB_ETC" "${legacy_ids[@]}"
        for id in "${legacy_ids[@]}"; do
            hits=$(awk 'function ip2n(s, a){split(s,a,".");return a[1]*16777216+a[2]*65536+a[3]*256+a[4]}
                NR==FNR { split($1,p,"/"); lo=ip2n(p[1]); n++; L[n]=lo; H[n]=lo+2^(32-p[2])-1; next }
                { split($1,p,"/"); x=ip2n(p[1]); for(i=1;i<=n;i++) if(x>=L[i] && x<=H[i]) { c++; break } }
                END { print c+0 }' "$LISTS_DIR/$id.v4" "$srcs")
            if [[ $hits -gt 0 ]]; then guess+=("$id"); fi
        done
    fi
    local isps=${OPT_ISPS:-$(IFS=,; echo "${guess[*]}")}
    say "  ISPs detected       : ${isps:-unknown}"
    [[ -n $isps ]] || die "could not infer ISPs; re-run: ir-isp-blocker migrate --isp mci,mtn"
    confirm "Import as a v2 rule and REMOVE the v1 chain? [y/N]: " || die "$(t aborted)"
    acquire_lock
    local s; s=$(stage_new)
    cfg_load "$s"; rules_load "$s"
    local p=all
    if [[ -n $ports ]]; then p=$(parse_ports "$ports") || die "bad ports in v1 chain"; else proto=any; fi
    [[ $mode == only && $p == all ]] && die "v1 only-mode rules without ports found; re-create manually"
    R_ID+=("$(rules_next_id)"); R_MODE+=("$mode"); R_ISPS+=("$isps"); R_PORTS+=("$p"); R_PROTO+=("$proto")
    R_DIR+=(in); R_ACTION+=(drop); R_RATE+=(30/minute); R_RAW+=(no); R_EXP+=(0)
    rules_save "$s"
    [[ -n $wl_ips ]] && tr ',' '\n' <<<"$wl_ips" >>"$s/whitelist.ips"
    # in only-mode the v1 port ACCEPTs without source were only the SSH port (already protected)
    [[ -n $wl_ports && $mode == block ]] && tr ',' '\n' <<<"$wl_ports" >>"$s/whitelist.ports"
    ensure_installed
    commit_stage "$s" "migrate-v1" || die "migration apply failed; v1 chain left untouched"
    [[ $DRY_RUN -eq 1 ]] && { echo "+ remove v1 chain $LEGACY_CHAIN"; return 0; }
    legacy_remove
}
legacy_remove() {
    ipt_del_jumps 4 filter INPUT "$LEGACY_CHAIN"
    iptables -w -F "$LEGACY_CHAIN" 2>/dev/null || true
    iptables -w -X "$LEGACY_CHAIN" 2>/dev/null || true
    local f
    for f in /etc/iptables/rules.v4 /etc/sysconfig/iptables; do
        if [[ ! -f $f ]] || ! grep -q "$LEGACY_CHAIN" "$f"; then continue; fi
        cp -- "$f" "$f.irb-v1.bak"
        awk -v c="$LEGACY_CHAIN" '!($0 ~ "^:"c" " || $0 ~ "^-A "c" " || $0 ~ "-j "c"$")' "$f.irb-v1.bak" >"$f"
        ok "removed v1 entries from $f (backup: $f.irb-v1.bak)"
    done
    ok "v1 chain '$LEGACY_CHAIN' removed"
}

# ------------------------------------------------------------------ option parsing
OPT_ISPS=""; OPT_ASNS=""; OPT_URL=""; OPT_FILE=""; OPT_NAME=""; OPT_PORTS=""; OPT_PROTO=""; OPT_DIR=""
OPT_ACTION=""; OPT_RATE=""; OPT_RAW=0; OPT_FOR=""; OPT_REPLACE=0; OPT_DEADMAN=""; OPT_SSHPORT=""
OPT_NOSSH=0; OPT_DOCKER=""; OPT_IPV6=""; OPT_RULE=""; OPT_ALL=0; OPT_TO=""; OPT_AUTO=""; OPT_KEEP_CONFIG=0
OPT_LIST=0
POS=()

parse_opts() {
    while [[ $# -gt 0 ]]; do
        case $1 in
            --isp|--isps) OPT_ISPS=${2:?--isp needs a value}; shift ;;
            --asn) OPT_ASNS=${2:?--asn needs a value}; shift ;;
            --list-url) OPT_URL=${2:?}; shift ;;
            --list-file) OPT_FILE=${2:?}; shift ;;
            --name) OPT_NAME=${2:?}; shift ;;
            --ports|--port|-p) OPT_PORTS=${2:?--ports needs a value}; shift ;;
            --proto) OPT_PROTO=${2:?}; shift ;;
            --direction|--dir) OPT_DIR=${2:?}; shift ;;
            --action) OPT_ACTION=${2:?}; shift ;;
            --drop) OPT_ACTION=drop ;;
            --reject) OPT_ACTION=reject ;;
            --log-only|--monitor) OPT_ACTION=log ;;
            --rate-limit) OPT_ACTION=ratelimit; OPT_RATE=${2:?--rate-limit needs N/unit}; shift ;;
            --raw) OPT_RAW=1 ;;
            --for) OPT_FOR=${2:?}; shift ;;
            --replace) OPT_REPLACE=1 ;;
            --rollback-after) OPT_DEADMAN=${2:?}; shift ;;
            --ssh-port) OPT_SSHPORT=${2:?}; shift ;;
            --no-ssh-protect) OPT_NOSSH=1 ;;
            --docker) OPT_DOCKER=${2:?}; shift ;;
            --ipv6) OPT_IPV6=${2:?}; shift ;;
            --rule) OPT_RULE=${2:?}; shift ;;
            --all) OPT_ALL=1 ;;
            --to) OPT_TO=${2:?}; shift ;;
            --list) OPT_LIST=1 ;;
            --auto) OPT_AUTO=${2:?--auto needs daily|weekly|off}; shift ;;
            --keep-config) OPT_KEEP_CONFIG=1 ;;
            --whitelist) OPT_WL=${2:?--whitelist needs IP[,IP]}; shift ;;
            --) shift; POS+=("$@"); break ;;
            -*) die "unknown option: $1 (see --help)" ;;
            *) POS+=("$1") ;;
        esac
        shift
    done
}

# apply option values that change global config into the stage
stage_apply_globals() { # stage
    local s=$1
    cfg_load "$s"
    if [[ -n $OPT_SSHPORT ]]; then CFG_SSH_PORTS=$(parse_ports "$OPT_SSHPORT") || die "bad --ssh-port"; fi
    [[ $OPT_NOSSH -eq 1 ]] && CFG_SSH_PROTECT=no
    if [[ -n $OPT_DOCKER ]]; then [[ $OPT_DOCKER =~ ^(auto|yes|no)$ ]] || die "bad --docker"; CFG_DOCKER=$OPT_DOCKER; fi
    if [[ -n $OPT_IPV6 ]]; then [[ $OPT_IPV6 =~ ^(yes|no)$ ]] || die "bad --ipv6"; CFG_IPV6=$OPT_IPV6; fi
    if [[ -n $OPT_BACKEND ]]; then CFG_BACKEND=$OPT_BACKEND; fi
    cfg_save "$s"
}

# collect ISP ids from --isp/--asn/--list-url/--list-file (creating custom lists as needed)
collect_isps() { # stage -> prints comma list
    local s=$1 ids=() id
    local items=() a
    if [[ -n $OPT_ISPS ]]; then
        split_csv items "${OPT_ISPS,,}"
        for id in "${items[@]}"; do
            [[ $id == parsan ]] && id=parsonline
            valid_id "$id" || die "invalid ISP id '$id'"
            if [[ -z ${ISP_EN[$id]:-} ]] && ! custom_lookup "$s" "$id" >/dev/null && [[ ! $id =~ ^as[0-9]+$ ]]; then
                die "unknown ISP '$id' (see: ir-isp-blocker list)"
            fi
            ids+=("$id")
        done
    fi
    if [[ -n $OPT_ASNS ]]; then
        split_csv items "$OPT_ASNS"
        for a in "${items[@]}"; do
            a=${a#AS}; a=${a#as}
            [[ $a =~ ^[1-9][0-9]{0,9}$ ]] || die "invalid ASN '$a'"
            ids+=("as$a")
            if ! custom_lookup "$s" "as$a" >/dev/null; then echo "as$a asn $a" >>"$s/custom.sources"; fi
        done
    fi
    if [[ -n $OPT_URL || -n $OPT_FILE ]]; then
        [[ -n $OPT_NAME ]] || die "--list-url/--list-file need --name NAME"
        local cid="c-${OPT_NAME,,}"
        valid_id "$cid" || die "invalid --name (use a-z, 0-9, '-', max 22 chars)"
        if [[ -n $OPT_URL ]]; then
            [[ $OPT_URL == https://* ]] || die "--list-url must be https://"
            import_custom "$cid" "$OPT_URL" >&2
            grep -v "^$cid " "$s/custom.sources" 2>/dev/null >"$s/custom.sources.tmp" || true
            echo "$cid url $OPT_URL" >>"$s/custom.sources.tmp"; mv -f -- "$s/custom.sources.tmp" "$s/custom.sources"
        else
            import_custom "$cid" "$OPT_FILE" >&2
            grep -v "^$cid " "$s/custom.sources" 2>/dev/null >"$s/custom.sources.tmp" || true
            echo "$cid file -" >>"$s/custom.sources.tmp"; mv -f -- "$s/custom.sources.tmp" "$s/custom.sources"
        fi
        ids+=("$cid")
    fi
    [[ ${#ids[@]} -gt 0 ]] || die "no ISP selected (use --isp, --asn, --list-url or --list-file)"
    printf '%s\n' "${ids[@]}" | awk '!seen[$0]++' | paste -sd, -
}

