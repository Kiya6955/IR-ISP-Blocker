    [[ -n $M_CLIENT ]] && info "$(t ssh_client "$M_CLIENT")"
    return 0
}

finish_change() { # stage reason
    ensure_installed
    commit_stage "$1" "$2" || die "apply failed (previous rules restored)"
    if [[ $DRY_RUN -eq 0 && -n $OPT_DEADMAN ]]; then
        [[ $OPT_DEADMAN =~ ^[0-9]+$ && $OPT_DEADMAN -ge 10 ]] || die "--rollback-after needs seconds >= 10"
        deadman_flow "$OPT_DEADMAN"
    fi
    legacy_notice
}

cmd_block_or_only() { # mode
    local mode=$1
    begin_change
    local s; s=$(stage_new)
    stage_apply_globals "$s"
    local isps; isps=$(collect_isps "$s")
    if [[ -n $OPT_WL ]]; then
        local wle=() e
        split_csv wle "$OPT_WL"
        for e in "${wle[@]}"; do
            valid_ip_any "$e" || die "invalid whitelist entry '$e'"
            grep -qxF -- "$e" "$s/whitelist.ips" 2>/dev/null || echo "$e" >>"$s/whitelist.ips"
        done
    fi
    rules_load "$s"
    [[ $OPT_REPLACE -eq 1 ]] && rules_clear
    local ports proto dir action rate raw=no exp=0
    if [[ -n $OPT_PORTS ]]; then ports=$(parse_ports "$OPT_PORTS") || die "invalid --ports '$OPT_PORTS'"; fi
    if [[ $mode == only ]]; then
        [[ -n ${ports:-} && $ports != all ]] || die "'only' needs explicit --ports (e.g. --ports 443,8443)"
    else
        [[ -n ${ports:-} ]] || ports=all
    fi
    proto=${OPT_PROTO:-}
    [[ -z $proto ]] && { if [[ $ports == all ]]; then proto=any; else proto=both; fi; }
    [[ $proto == all ]] && proto=both
    dir=${OPT_DIR:-in}; action=${OPT_ACTION:-drop}; rate=${OPT_RATE:-30/minute}
    [[ $OPT_RAW -eq 1 ]] && raw=yes
    if [[ -n $OPT_FOR ]]; then
        local secs; secs=$(parse_duration "$OPT_FOR") || die "invalid --for (use e.g. 90m, 24h, 2d)"
        exp=$(( $(date +%s) + secs ))
    fi
    local msg
    msg=$(rule_check "$mode" "$isps" "$ports" "$proto" "$dir" "$action" "$rate" "$raw" "$exp") || die "$msg"
    R_ID+=("$(rules_next_id)"); R_MODE+=("$mode"); R_ISPS+=("$isps"); R_PORTS+=("$ports"); R_PROTO+=("$proto")
    R_DIR+=("$dir"); R_ACTION+=("$action"); R_RATE+=("$rate"); R_RAW+=("$raw"); R_EXP+=("$exp")
    rules_save "$s"
    local i names=() idl=()
    split_csv idl "$isps"
    for i in "${idl[@]}"; do names+=("$(isp_name "$i")"); done
    info "$mode: ${names[*]} | ports=$ports proto=$proto dir=$dir action=$action$([[ $exp != 0 ]] && echo " until $(date -d "@$exp" 2>/dev/null || echo "$exp")")"
    finish_change "$s" "$mode $isps $ports"
}

cmd_settings() { # apply --ipv6/--backend/--docker/--ssh-port changes to the saved configuration
    begin_change
    local s; s=$(stage_new)
    stage_apply_globals "$s"
    rules_load "$s"
    finish_change "$s" "settings"
}

cmd_unblock() {
    begin_change
    local s; s=$(stage_new)
    stage_apply_globals "$s"
    rules_load "$s"
    if [[ $OPT_ALL -eq 1 || ${OPT_ISPS,,} == all ]]; then
        rules_clear
    elif [[ -n $OPT_RULE ]]; then
        local i hit=0
        for i in "${!R_ID[@]}"; do [[ ${R_ID[i]} == "$OPT_RULE" ]] && { rules_remove_index "$i"; hit=1; break; }; done
        [[ $hit -eq 1 ]] || die "no rule with id $OPT_RULE (see: ir-isp-blocker status)"
    elif [[ -n $OPT_ISPS || -n $OPT_ASNS ]]; then
        local rm="," a items=() id
        split_csv items "${OPT_ISPS,,}"
        for a in "${items[@]}"; do [[ $a == parsan ]] && a=parsonline; rm+="$a,"; done
        split_csv items "$OPT_ASNS"
        for a in "${items[@]}"; do a=${a#AS}; a=${a#as}; rm+="as$a,"; done
        local i=$(( ${#R_ID[@]} - 1 ))
        while (( i >= 0 )); do
            local keep=()
            split_csv items "${R_ISPS[i]}"
            for id in "${items[@]}"; do [[ $rm == *",$id,"* ]] || keep+=("$id"); done
            if [[ ${#keep[@]} -eq 0 ]]; then rules_remove_index "$i"
            else R_ISPS[i]=$(IFS=,; echo "${keep[*]}"); fi
            i=$((i - 1))
        done
    else
        die "unblock needs --isp X[,Y], --rule N or --all"
    fi
    rules_save "$s"
    finish_change "$s" "unblock"
}

cmd_apply() { # re-apply current configuration (also used at boot via 'restore')
    local offline=${1:-0}
    if [[ $DRY_RUN -eq 0 ]]; then need_root; acquire_lock; fi
    prepare_lists_dir_for_dryrun
    index_load || true
    [[ $offline -eq 1 ]] || M_CLIENT=$(detect_ssh_client)
    local s; s=$(stage_new)
    rules_load "$s"
    prune_expired_in_stage "$s"
    commit_stage "$s" "${2:-apply}"
}

prune_expired_in_stage() { # stage
    local s=$1 now i changed=0
    now=$(date +%s)
    i=$(( ${#R_ID[@]} - 1 ))
    while (( i >= 0 )); do
        if [[ ${R_EXP[i]} != 0 ]] && (( R_EXP[i] <= now )); then
            info "rule ${R_ID[i]} expired"; rules_remove_index "$i"; changed=1
        fi
        i=$((i - 1))
    done
    [[ $changed -eq 1 ]] && rules_save "$s"
    return 0
}

cmd_expire() {
    need_root
    rules_load "$IRB_ETC"
    local now i due=0
    now=$(date +%s)
    for i in "${!R_ID[@]}"; do [[ ${R_EXP[i]} != 0 ]] && (( R_EXP[i] <= now )) && due=1; done
    [[ $due -eq 1 ]] || return 0
    cmd_apply 1 expire
}

cmd_update() {
    if [[ -n $OPT_AUTO ]]; then
        need_root; acquire_lock
        [[ $OPT_AUTO =~ ^(off|daily|weekly)$ ]] || die "--auto must be daily, weekly or off"
        mkdir -p -- "$IRB_ETC"
        cfg_load "$IRB_ETC"; CFG_AUTO_UPDATE=$OPT_AUTO; cfg_save "$IRB_ETC"
        rules_load "$IRB_ETC"
        ensure_installed
        sync_timers
        ok "auto-update: $OPT_AUTO"
        return 0
    fi
    if [[ $DRY_RUN -eq 0 ]]; then need_root; acquire_lock; mkdir -p -- "$LISTS_DIR"; fi
    prepare_lists_dir_for_dryrun
    cfg_load "$IRB_ETC"
    ensure_downloader
    if lists_update; then ok "$(t lists_updated)"; else warn "$(t lists_kept)"; fi
    # refresh custom ASN/URL lists
    if [[ -f $IRB_ETC/custom.sources ]]; then
        local id typ val
        while read -r id typ val; do
            case $typ in
                asn) fetch_asn "$val" || warn "refresh of $id failed; keeping old copy" ;;
                url) import_custom "$id" "$val" || warn "refresh of $id failed; keeping old copy" ;;
            esac
        done <"$IRB_ETC/custom.sources"
    fi
    index_load || true
    rules_load "$IRB_ETC"
    if [[ ${#R_ID[@]} -gt 0 ]]; then
        local s; s=$(stage_new)
        prune_expired_in_stage "$s"
        commit_stage "$s" "update"
    fi
}

cmd_restore() { # boot-time: offline re-apply from cached lists
