# Rules: one per line: id=N mode=block|only isps=a,b ports=all|spec proto=tcp|udp|both|any
#                      dir=in|out|both action=drop|reject|log|ratelimit rate=N/unit raw=yes|no expires=EPOCH
R_ID=(); R_MODE=(); R_ISPS=(); R_PORTS=(); R_PROTO=(); R_DIR=(); R_ACTION=(); R_RATE=(); R_RAW=(); R_EXP=()

rules_clear() { R_ID=(); R_MODE=(); R_ISPS=(); R_PORTS=(); R_PROTO=(); R_DIR=(); R_ACTION=(); R_RATE=(); R_RAW=(); R_EXP=(); }

# rule_check MODE ISPS PORTS PROTO DIR ACTION RATE RAW EXP -> error message on stdout if invalid
rule_check() {
    local mode=$1 isps=$2 ports=$3 proto=$4 dir=$5 action=$6 rate=$7 raw=$8 exp=$9 i
    [[ $mode =~ ^(block|only)$ ]] || { echo "bad mode '$mode'"; return 1; }
    [[ -n $isps ]] || { echo "no ISPs"; return 1; }
    local ids=()
    split_csv ids "$isps"
    [[ ${#ids[@]} -gt 0 ]] || { echo "no ISPs"; return 1; }
    for i in "${ids[@]}"; do valid_id "$i" || { echo "bad ISP id '$i'"; return 1; }; done
    [[ $ports == all ]] || [[ $(parse_ports "$ports" 2>/dev/null) == "$ports" ]] || { echo "bad ports '$ports'"; return 1; }
    [[ $proto =~ ^(tcp|udp|both|any)$ ]] || { echo "bad proto '$proto'"; return 1; }
    [[ $proto == any && $ports != all ]] && { echo "proto 'any' requires ports=all"; return 1; }
    [[ $dir =~ ^(in|out|both)$ ]] || { echo "bad direction '$dir'"; return 1; }
    [[ $action =~ ^(drop|reject|log|ratelimit)$ ]] || { echo "bad action '$action'"; return 1; }
    [[ $rate =~ ^[1-9][0-9]{0,6}/(second|minute|hour|day)$ ]] || { echo "bad rate '$rate'"; return 1; }
    [[ $raw =~ ^(yes|no)$ ]] || { echo "bad raw '$raw'"; return 1; }
    [[ $exp =~ ^[0-9]{1,12}$ ]] || { echo "bad expires '$exp'"; return 1; }
    if [[ $raw == yes ]]; then
        [[ $dir == out ]] && { echo "raw mode only applies to inbound traffic"; return 1; }
        [[ $action =~ ^(drop|log)$ ]] || { echo "raw mode supports only drop/log (no conntrack there)"; return 1; }
        [[ $mode == block ]] || { echo "raw mode supports only 'block' rules"; return 1; }
    fi
    [[ $mode == only && $dir != in ]] && { echo "'only' mode is inbound-only"; return 1; }
    return 0
}

rules_load() { # dir
    rules_clear
    local f="$1/rules.conf" line tok k v n=0 msg
    [[ -f $f ]] || return 0
    while IFS= read -r line || [[ -n $line ]]; do
        n=$((n + 1))
        line=${line%%#*}
        [[ -z ${line//[$'\t\r ']/} ]] && continue
        local id="" mode=block isps="" ports=all proto=any dir=in action=drop rate=30/minute raw=no exp=0 toks=()
        read -r -a toks <<<"$line"
        for tok in "${toks[@]}"; do
            k=${tok%%=*}; v=${tok#*=}
            case $k in
                id) id=$v ;; mode) mode=$v ;; isps) isps=$v ;; ports) ports=$v ;; proto) proto=$v ;;
                dir) dir=$v ;; action) action=$v ;; rate) rate=$v ;; raw) raw=$v ;; expires) exp=$v ;;
                *) die "$f:$n: unknown field '$k'" ;;
            esac
        done
        [[ $id =~ ^[1-9][0-9]{0,4}$ ]] || die "$f:$n: bad rule id"
        msg=$(rule_check "$mode" "$isps" "$ports" "$proto" "$dir" "$action" "$rate" "$raw" "$exp") || die "$f:$n: $msg"
        R_ID+=("$id"); R_MODE+=("$mode"); R_ISPS+=("$isps"); R_PORTS+=("$ports"); R_PROTO+=("$proto")
        R_DIR+=("$dir"); R_ACTION+=("$action"); R_RATE+=("$rate"); R_RAW+=("$raw"); R_EXP+=("$exp")
    done <"$f"
}
