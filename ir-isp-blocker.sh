    [[ -d $IRB_ETC/state/applied ]] && cp -R -- "$IRB_ETC/state/applied" "$d/applied"
    if have nft; then nft list table inet "$NFT_TABLE" >"$d/live-nft.txt" 2>/dev/null || rm -f -- "$d/live-nft.txt"; fi
    if have iptables-save; then iptables-save >"$d/live-iptables.txt" 2>/dev/null || true; fi
    if have ip6tables-save; then ip6tables-save >"$d/live-ip6tables.txt" 2>/dev/null || true; fi
    printf '%s\n' "$1" >"$d/reason"
    # prune old backups
    local all=()
    mapfile -t all < <(ls -1 "$IRB_ETC/backups" 2>/dev/null | sort)
    while [[ ${#all[@]} -gt $MAX_BACKUPS ]]; do rm -rf -- "${IRB_ETC:?}/backups/${all[0]}"; all=("${all[@]:1}"); done
    echo "$id"
}

# commit_stage STAGE REASON [no-backup] : generate, (dry-run print), backup, apply, commit config
LAST_BACKUP=""
commit_stage() {
    local s=$1 reason=$2 f
    cfg_load "$s"
    rules_load "$s"
    pick_backend
    build_model "$s"
    case $reason in
        restore|expire|update|rollback-*) safety_check soft ;;
        *) safety_check ;;
    esac
    # remember detected SSH ports so boot-time restore never depends on detection
    if [[ -n $M_SSH && $M_SSH != "$CFG_SSH_PORTS" ]]; then CFG_SSH_PORTS=$M_SSH; cfg_save "$s"; fi
    local out="$WORK/artifacts"
    rm -rf -- "$out"
    gen_all "$out"
    if [[ $DRY_RUN -eq 1 ]]; then
        say "$(t dry_header)"
        say "# backend=$BACKEND ipv6=$CFG_IPV6 forward-hook=$M_FWD ssh-ports=${M_SSH:-none} rules=${#R_ID[@]}"
        print_artifacts "$out"
        return 0
    fi
    mkdir -p -- "$IRB_ETC/state"
    if [[ $reason != restore ]]; then LAST_BACKUP=$(backup_now "$reason"); fi
    if ! apply_artifacts "$out"; then
        err "apply failed; restoring previous state"
        if [[ -d $IRB_ETC/state/applied ]]; then apply_artifacts "$IRB_ETC/state/applied" || err "could not restore previous rules - run: ir-isp-blocker doctor"; fi
        return 1
    fi
    for f in "${CONF_FILES[@]}"; do
        if [[ -f $s/$f ]]; then { cp -- "$s/$f" "$IRB_ETC/$f.tmp" && mv -f -- "$IRB_ETC/$f.tmp" "$IRB_ETC/$f"; } || die "cannot write $IRB_ETC/$f"
        else rm -f -- "$IRB_ETC/$f"; fi
    done
    rm -rf -- "$IRB_ETC/state/applied"; cp -R -- "$out" "$IRB_ETC/state/applied"
    if [[ -n ${M_CLIENT:-} ]]; then remember_client "$M_CLIENT"; fi
    if [[ ${#R_ID[@]} -eq 0 ]]; then ok "$(t nothing_active)"; else ok "$(t applied "$BACKEND")"; fi
    have logger && logger -t ir-isp-blocker "applied ($reason): backend=$BACKEND rules=${#R_ID[@]}" 2>/dev/null || true
    sync_timers
    return 0
}

remember_client() { # keep the 5 most recent SSH client IPs as automatic whitelist entries
    local f="$IRB_ETC/state/auto-whitelist" ip=$1
    mkdir -p -- "$IRB_ETC/state"
    { echo "$ip"; [[ -f $f ]] && grep -vxF -- "$ip" "$f"; } | head -5 >"$f.tmp" || true
    mv -f -- "$f.tmp" "$f"
}

# ------------------------------------------------------------------ persistence / install
self_source() { # prints path to a copy of this script
    mkwork
    local src=${BASH_SOURCE[0]:-$0}
    if [[ -f $src && -r $src ]] && grep -q '^IRB_VERSION=' "$src"; then echo "$src"; return 0; fi
    # running from a pipe (bash <(curl ...)): download a copy
    local tmp="$WORK/self.sh"
    fetch "$(raw_base)/ir-isp-blocker.sh" "$tmp" || return 1
    if ! bash -n "$tmp" || ! grep -q '^IRB_VERSION=' "$tmp"; then err "downloaded script failed validation"; return 1; fi
    echo "$tmp"
}

has_systemd() { [[ -d /run/systemd/system ]] && have systemctl; }

write_unit() { # name content
    local p="$IRB_SYSTEMD_DIR/$1"
    if [[ ! -f $p ]] || [[ $(cat -- "$p") != "$2" ]]; then printf '%s\n' "$2" >"$p"; return 0; fi
    return 1
}

