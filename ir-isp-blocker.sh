# Download SHA256SUMS + index into a staging dir, verify, then move into LISTS_DIR.
# Also refreshes every list already cached plus any extra ids passed as arguments.
lists_update() { # [extra ids...]
    mkwork
    local stage="$WORK/lists-stage" base id f want=() h
    rm -rf -- "$stage"; mkdir -p -- "$stage" "$LISTS_DIR"
    base="$(raw_base)/lists"
    fetch "$base/SHA256SUMS" "$stage/SHA256SUMS" || return 1
    # SHA256SUMS must look like "<64 hex>  <name>" only
    if ! awk 'NF!=2 || $1 !~ /^[0-9a-f]+$/ || length($1)!=64 || $2 !~ /^[a-z0-9.-]+$/ {exit 1}' "$stage/SHA256SUMS"; then
        err "SHA256SUMS is malformed (got an error page?)"; return 1
    fi
    want=(index.tsv)
    for f in "$LISTS_DIR"/*.v4 "$LISTS_DIR"/*.v6; do
        [[ -e $f ]] || continue
        f=${f##*/}
        grep -q "  $f\$" "$stage/SHA256SUMS" && want+=("$f")
    done
    for id in "$@"; do want+=("$id.v4" "$id.v6"); done
    local seen=" "
    for f in "${want[@]}"; do
        [[ $seen == *" $f "* ]] && continue
        seen+="$f "
        h=$(awk -v n="$f" '$2==n {print $1}' "$stage/SHA256SUMS")
        [[ -n $h ]] || { err "list '$f' is not published upstream"; return 1; }
        fetch "$base/$f" "$stage/$f" || return 1
        [[ $(sha256_of "$stage/$f") == "$h" ]] || { err "checksum mismatch for $f"; return 1; }
        if [[ $f == *.v4 ]]; then cidr_canon 4 1 "$MIN_V4_PREFIX" 0 <"$stage/$f" >/dev/null || { err "$f: invalid content"; return 1; }; fi
        if [[ $f == *.v6 ]]; then cidr_canon 6 1 0 "$MIN_V6_PREFIX" <"$stage/$f" >/dev/null || { err "$f: invalid content"; return 1; }; fi
    done
    # everything verified: commit (per-file atomic rename)
    for f in "${want[@]}" SHA256SUMS; do
        [[ -f $stage/$f ]] || continue
        mv -f -- "$stage/$f" "$LISTS_DIR/$f"
    done
    return 0
}

ensure_index() {
    if [[ ! -f $LISTS_DIR/index.tsv ]]; then
        info "Fetching ISP catalogue..."
        lists_update || die "could not download the ISP catalogue from $(raw_base)"
    fi
    index_load || die "ISP catalogue $LISTS_DIR/index.tsv is empty or unreadable"
}

# fetch_asn N -> writes $LISTS_DIR/asN.v4/.v6 from RIPEstat (live)
fetch_asn() {
    local n=$1 id="as$1" j holder
    [[ $n =~ ^[1-9][0-9]{0,9}$ ]] || die "bad ASN '$n'"
    mkwork
    j="$WORK/as$n.json"
    fetch "$IRB_RIPESTAT/as-overview/data.json?resource=AS$n&sourceapp=ir-isp-blocker" "$j" || die "RIPEstat request failed"
    holder=$(grep -o '"holder" *: *"[^"]*"' "$j" | head -1 | sed 's/.*: *"//; s/"$//' | tr -cd '[:alnum:] .,()&-' | cut -c1-80 || true)
    info "AS$n holder (RIPEstat): ${holder:-unknown}"
    fetch "$IRB_RIPESTAT/announced-prefixes/data.json?resource=AS$n&sourceapp=ir-isp-blocker" "$j" || die "RIPEstat request failed"
    grep -q '"status" *: *"ok"' "$j" || die "RIPEstat returned an error for AS$n"
    local raw="$WORK/as$n.raw"
    grep -o '"prefix" *: *"[^"]*"' "$j" | sed 's/.*: *"//; s/"$//' >"$raw" || true
    [[ -s $raw ]] || die "AS$n announces no prefixes"
    local canon
    canon=$(cidr_canon any 0 "$MIN_V4_PREFIX" "$MIN_V6_PREFIX" <"$raw") || die "AS$n: invalid data"
    mkdir -p -- "$LISTS_DIR"
    printf '%s\n' "$canon" | awk '$1==4{print $2}' >"$LISTS_DIR/$id.v4"
    printf '%s\n' "$canon" | awk '$1==6{print $2}' >"$LISTS_DIR/$id.v6"
    ok "AS$n: $(wc -l <"$LISTS_DIR/$id.v4") IPv4 / $(wc -l <"$LISTS_DIR/$id.v6") IPv6 prefixes"
}

# import_custom ID SRC(url|path) -> $LISTS_DIR/ID.v4/.v6 (strict validation of every line)
import_custom() {
    local id=$1 src=$2 tmp canon
    mkwork
    tmp="$WORK/custom-$id"
    if [[ $src == https://* ]]; then
        [[ $src =~ ^https://[A-Za-z0-9._~:/?#@!\$\&\'()*+,\;=%-]+$ ]] || die "URL contains unsupported characters"
        fetch "$src" "$tmp" || die "download failed: $src"
    else
        [[ -f $src && -r $src ]] || die "cannot read $src"
        cp -- "$src" "$tmp"
    fi
    canon=$(cidr_canon any 1 "$MIN_V4_PREFIX" "$MIN_V6_PREFIX" <"$tmp") ||
        die "custom list '$id' rejected: every non-comment line must be a valid IP/CIDR (an HTML error page?)"
    [[ -n $canon ]] || die "custom list '$id' is empty"
    mkdir -p -- "$LISTS_DIR"
    printf '%s\n' "$canon" | awk '$1==4{print $2}' >"$LISTS_DIR/$id.v4"
    printf '%s\n' "$canon" | awk '$1==6{print $2}' >"$LISTS_DIR/$id.v6"
    ok "custom list $id: $(wc -l <"$LISTS_DIR/$id.v4") IPv4 / $(wc -l <"$LISTS_DIR/$id.v6") IPv6 entries"
}

# make sure list files exist for the given ids (dir = config dir for custom.sources)
ensure_lists() { # dir ids...
    local dir=$1 id missing=() src
    shift
    for id in "$@"; do
        [[ -f $LISTS_DIR/$id.v4 && -f $LISTS_DIR/$id.v6 ]] && continue
        if src=$(custom_lookup "$dir" "$id"); then
            case ${src%% *} in
                asn) fetch_asn "${src#* }" ;;
                url) import_custom "$id" "${src#* }" ;;
                *) die "custom list '$id' is missing from $LISTS_DIR and has no source to re-fetch" ;;
            esac
        elif [[ -n ${ISP_EN[$id]:-} ]]; then
            missing+=("$id")
        elif [[ $id =~ ^as([0-9]+)$ ]]; then
            fetch_asn "${BASH_REMATCH[1]}"
        else
            die "unknown ISP id '$id' (see: ir-isp-blocker list)"
        fi
    done
    if [[ ${#missing[@]} -gt 0 ]]; then
        lists_update "${missing[@]}" || die "could not download lists: ${missing[*]}"
    fi
}

# ------------------------------------------------------------------ system detection
detect_ssh_ports() { # prints spec of detected ports (may be empty)
    local found=() p f files=()
    [[ -r $IRB_SSHD_CONFIG ]] && files+=("$IRB_SSHD_CONFIG")
    for f in "${IRB_SSHD_CONFIG%/*}"/sshd_config.d/*.conf; do [[ -r $f ]] && files+=("$f"); done
    if [[ ${#files[@]} -gt 0 ]]; then
        while read -r p; do [[ $p =~ ^[0-9]+$ ]] && found+=("$p"); done < <(
            awk 'tolower($1)=="port"{print $2} tolower($1)=="listenaddress"{ if (match($2,/:[0-9]+$/)) print substr($2,RSTART+1) }' "${files[@]}" 2>/dev/null || true)
    fi
    if have ss; then
        while read -r p; do [[ $p =~ ^[0-9]+$ ]] && found+=("$p"); done < <(
            ss -Hltnp 2>/dev/null | awk '/"sshd/ { n=split($4,a,":"); print a[n] }' || true)
    fi
    if [[ ${#found[@]} -eq 0 ]] && { [[ -r $IRB_SSHD_CONFIG ]] || have sshd; }; then found+=(22); fi
    [[ -n $CFG_SSH_PORTS ]] && found+=("$CFG_SSH_PORTS")
    [[ ${#found[@]} -eq 0 ]] && return 0
    local IFS=,
    parse_ports "${found[*]}" 2>/dev/null || true
}

detect_ssh_client() { # prints client IP of the current SSH session, if any
    local ip=""
    if [[ -n ${SSH_CONNECTION:-} ]]; then ip=${SSH_CONNECTION%% *}
    elif [[ -n ${SSH_CLIENT:-} ]]; then ip=${SSH_CLIENT%% *}
    elif have who; then ip=$(who -m 2>/dev/null | sed -n 's/.*(\([0-9a-fA-F.:]*\)).*/\1/p' | head -1 || true)
    fi
    ip=${ip#::ffff:}
    [[ -n $ip ]] && valid_ip_any "$ip" && echo "$ip"
    return 0
}

detect_docker() {
    case $CFG_DOCKER in yes) return 0 ;; no) return 1 ;; esac
    [[ -S /var/run/docker.sock ]] || have dockerd || have docker
}

virt_kind() {
    if have systemd-detect-virt; then systemd-detect-virt 2>/dev/null || true
