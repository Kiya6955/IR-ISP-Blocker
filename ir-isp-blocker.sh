backend_usable() { # name
    case $1 in
        nft)
            have nft || return 1
            [[ ${IRB_SKIP_PROBE:-0} == 1 ]] && return 0
            printf '%s\n' "$NFT_PROBE" | nft -c -f - >/dev/null 2>&1 ;;
        ipset)
            have iptables && have ipset && have iptables-restore || return 1
            [[ ${IRB_SKIP_PROBE:-0} == 1 ]] && return 0
            ipset list -n >/dev/null 2>&1 && iptables -w -n -L INPUT >/dev/null 2>&1 ;;
        iptables)
            have iptables && have iptables-restore || return 1
            [[ ${IRB_SKIP_PROBE:-0} == 1 ]] && return 0
            iptables -w -n -L INPUT >/dev/null 2>&1 ;;
        *) return 1 ;;
    esac
}

BACKEND=""
pick_backend() {
    local wanted=${OPT_BACKEND:-${IRB_BACKEND:-$CFG_BACKEND}}
    if [[ $wanted != auto ]]; then
        if [[ $DRY_RUN -eq 1 ]] || backend_usable "$wanted"; then BACKEND=$wanted; return 0; fi
        die "requested backend '$wanted' is not usable on this system (see: ir-isp-blocker doctor)"
    fi
    local b
    for b in nft ipset iptables; do
        if backend_usable "$b"; then BACKEND=$b; break; fi
    done
    if [[ -z $BACKEND ]]; then
        [[ $DRY_RUN -eq 1 ]] && { BACKEND=nft; warn "no usable backend found; dry-run shows nftables output"; return 0; }
        install_prereqs && pick_backend_noinstall
    fi
    [[ $BACKEND == iptables ]] && warn "ipset not available: using plain iptables (one rule per CIDR - slower). Install ipset or nftables for best performance."
    return 0
}
pick_backend_noinstall() {
    local b
    for b in nft ipset iptables; do backend_usable "$b" && { BACKEND=$b; return 0; }; done
    local v; v=$(virt_kind)
    die "no usable firewall backend (nftables / iptables). Virtualization: ${v:-unknown}. OpenVZ/LXC containers often cannot load netfilter modules - ask your provider."
}

pkg_install() { # packages...
    if have apt-get; then run env DEBIAN_FRONTEND=noninteractive apt-get update -qq && run env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "$@"
    elif have dnf; then run dnf install -y -q "$@"
    elif have yum; then run yum install -y -q "$@"
    elif have pacman; then run pacman -S --noconfirm --needed "$@"
    elif have apk; then run apk add --no-cache "$@"
    elif have zypper; then run zypper -n -q install "$@"
    else err "no supported package manager (apt/dnf/yum/pacman/apk/zypper) found"; return 1; fi
}

install_prereqs() {
