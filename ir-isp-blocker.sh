mkwork() {
    # shellcheck disable=SC2031  # run_sub deliberately gives subshells their own WORK
    [[ -n $WORK ]] && return 0
    WORK=$(mktemp -d "${TMPDIR:-/tmp}/irb.XXXXXX")
}

is_root() { [[ ${IRB_ASSUME_ROOT:-0} == 1 || $(id -u) -eq 0 ]]; }
need_root() { is_root || die "$(t need_root)"; }

acquire_lock() {
    [[ $LOCK_HELD -ne 0 || $DRY_RUN -eq 1 ]] && return 0
    mkdir -p -- "$(dirname -- "$IRB_LOCK")" 2>/dev/null || true
    if have flock; then
        exec 9>"$IRB_LOCK"
        flock -n 9 || die "another ir-isp-blocker instance is running (lock: $IRB_LOCK)"
        LOCK_HELD=1
    else
        if ! mkdir -- "$IRB_LOCK.d" 2>/dev/null; then
            local pid=""
            pid=$(cat -- "$IRB_LOCK.d/pid" 2>/dev/null || true)
            if [[ $pid =~ ^[0-9]+$ ]] && ! kill -0 "$pid" 2>/dev/null; then
                rm -rf -- "$IRB_LOCK.d"; mkdir -- "$IRB_LOCK.d" 2>/dev/null || die "cannot take lock $IRB_LOCK.d"
            else
                die "another instance is running (lock: $IRB_LOCK.d)"
            fi
        fi
        echo "${BASHPID:-$$}" >"$IRB_LOCK.d/pid"
        LOCK_HELD=2
    fi
}

