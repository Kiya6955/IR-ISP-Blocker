    fi
}

begin_change() { # common start of mutating commands
    if [[ $DRY_RUN -eq 0 ]]; then need_root; acquire_lock; mkdir -p -- "$IRB_ETC" "$LISTS_DIR"; fi
    prepare_lists_dir_for_dryrun
    ensure_downloader
    ensure_index
