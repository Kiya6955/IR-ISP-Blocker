}

cmd_rollback() {
    local b
    if [[ $OPT_LIST -eq 1 || ${POS[0]:-} == list ]]; then
        ls -1 "$IRB_ETC/backups" 2>/dev/null | sort -r | while read -r b; do
            printf '%s  %s\n' "$b" "$(cat "$IRB_ETC/backups/$b/reason" 2>/dev/null)"
        done
        return 0
    fi
    if [[ $DRY_RUN -eq 0 ]]; then need_root; acquire_lock; fi
    b=${OPT_TO:-$(ls -1 "$IRB_ETC/backups" 2>/dev/null | sort | tail -1)}
    [[ -n $b && $b =~ ^[0-9-]+$ && -d $IRB_ETC/backups/$b ]] || die "no such backup '${b:-}' (see: ir-isp-blocker rollback --list)"
    [[ $QUIET -eq 1 ]] || say "Rolling back to $b ($(cat "$IRB_ETC/backups/$b/reason" 2>/dev/null))"
    confirm "$(t confirm_q)" || die "$(t aborted)"
    deadman_cancel || true
    prepare_lists_dir_for_dryrun
    index_load || true
    mkwork
    local s="$WORK/stage" f
    rm -rf -- "$s"; mkdir -p -- "$s"
    for f in "${CONF_FILES[@]}"; do [[ -f $IRB_ETC/backups/$b/$f ]] && cp -- "$IRB_ETC/backups/$b/$f" "$s/$f"; done
    cfg_load "$s"
    rules_load "$s"
    # Prefer the exact artifacts that were live at backup time (no list/network dependency)
    if [[ -d $IRB_ETC/backups/$b/applied && $DRY_RUN -eq 0 ]] && backend_usable "$(cat "$IRB_ETC/backups/$b/applied/backend")"; then
        LAST_BACKUP=$(backup_now "pre-rollback")
        apply_artifacts "$IRB_ETC/backups/$b/applied" || die "rollback apply failed"
        for f in "${CONF_FILES[@]}"; do
            if [[ -f $s/$f ]]; then cp -- "$s/$f" "$IRB_ETC/$f"; else rm -f -- "$IRB_ETC/$f"; fi
        done
        rm -rf -- "$IRB_ETC/state/applied"; cp -R -- "$IRB_ETC/backups/$b/applied" "$IRB_ETC/state/applied"
        sync_timers
    elif [[ ! -d $IRB_ETC/backups/$b/applied ]]; then
        # backup taken before anything was applied -> previous state was "no rules"
        rules_clear; rules_save "$s"
        commit_stage "$s" "rollback-$b"
    else
        commit_stage "$s" "rollback-$b"
    fi
    have logger && logger -t ir-isp-blocker "rolled back to $b" 2>/dev/null || true
    ok "$(t rolled_back)"
}

