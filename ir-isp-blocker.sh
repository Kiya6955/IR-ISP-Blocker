    cfg_defaults
    local f="$1/config" line k v n=0
    [[ -f $f ]] || return 0
    while IFS= read -r line || [[ -n $line ]]; do
        n=$((n + 1))
        line=${line%%#*}; line=${line//[$'\t\r ']/}
        [[ -z $line ]] && continue
        [[ $line == *=* ]] || die "$f:$n: expected KEY=VALUE"
        k=${line%%=*}; v=${line#*=}; v=${v//\"/}
        case $k in
            BACKEND)     [[ $v =~ ^(auto|nft|ipset|iptables)$ ]] || die "$f:$n: bad BACKEND"; CFG_BACKEND=$v ;;
            IPV6)        [[ $v =~ ^(yes|no)$ ]] || die "$f:$n: bad IPV6"; CFG_IPV6=$v ;;
            DOCKER)      [[ $v =~ ^(auto|yes|no)$ ]] || die "$f:$n: bad DOCKER"; CFG_DOCKER=$v ;;
            LANG)        ;;  # legacy key from earlier v2 builds, ignored
            SSH_PORTS)   [[ -z $v ]] || v=$(parse_ports "$v") || die "$f:$n: bad SSH_PORTS"; CFG_SSH_PORTS=$v ;;
            SSH_PROTECT) [[ $v =~ ^(yes|no)$ ]] || die "$f:$n: bad SSH_PROTECT"; CFG_SSH_PROTECT=$v ;;
            AUTO_UPDATE) [[ $v =~ ^(off|daily|weekly)$ ]] || die "$f:$n: bad AUTO_UPDATE"; CFG_AUTO_UPDATE=$v ;;
            RAW_BASE)    [[ -z $v || $v =~ ^(https|file)://[A-Za-z0-9._~:/%+-]+$ ]] || die "$f:$n: bad RAW_BASE"; CFG_RAW_BASE=$v ;;
            *) warn "$f:$n: unknown key '$k' ignored" ;;
        esac
    done <"$f"
}
