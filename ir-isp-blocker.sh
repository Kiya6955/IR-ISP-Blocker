}

NFT_PROBE='table inet irb_probe {
  set s { type ipv4_addr; flags interval; auto-merge; elements = { 192.0.2.0/24, 192.0.2.128/25 } }
  set d { type ipv4_addr; size 1024; flags dynamic,timeout; timeout 60s; }
  chain c { type filter hook input priority -10; policy accept;
