# ------------------------------------------------------------------ main
main() {
    local args=() a cmd=""
    while [[ $# -gt 0 ]]; do
        a=$1
        case $a in
            --dry-run|-n) DRY_RUN=1 ;;
            --yes|-y) ASSUME_YES=1 ;;
            --quiet|-q) QUIET=1 ;;
            --force) FORCE=1 ;;
            --no-color) NO_COLOR=1; setup_colors ;;
            --backend) OPT_BACKEND=${2:?}; shift; [[ $OPT_BACKEND =~ ^(auto|nft|ipset|iptables)$ ]] || die "bad --backend" ;;
            -h|--help) usage; exit 0 ;;
            -V|--version) echo "ir-isp-blocker $IRB_VERSION"; exit 0 ;;
            *) args+=("$a") ;;
        esac
        shift
    done
    [[ $OPT_BACKEND == auto ]] && OPT_BACKEND=""
    if [[ ${#args[@]} -eq 0 ]]; then
        if [[ -t 0 && -t 1 ]]; then interactive; else usage; fi
        exit 0
    fi
    cmd=${args[0]}
    parse_opts "${args[@]:1}"
    case $cmd in block|only|unblock|apply|update|install|settings|whitelist|import) auto_migrate_legacy ;; esac
    case $cmd in
        block)      cmd_block_or_only block ;;
        only)       cmd_block_or_only only ;;
        unblock)    cmd_unblock ;;
        status)     cmd_status ;;
        list)       cmd_list ;;
        update)     cmd_update ;;
        whitelist)  cmd_whitelist ;;
        rollback)   cmd_rollback ;;
        confirm)    cmd_confirm ;;
        apply)      cmd_apply 0 apply ;;
        restore)    cmd_restore ;;
        expire)     cmd_expire ;;
        migrate)    cmd_migrate ;;
        settings)   cmd_settings ;;
        doctor)     cmd_doctor ;;
        export)     cmd_export ;;
        import)     cmd_import ;;
        install)    cmd_install ;;
        uninstall)  cmd_uninstall ;;
        help)       usage ;;
        version)    echo "ir-isp-blocker $IRB_VERSION" ;;
        *) die "unknown command '$cmd' (see --help)" ;;
    esac
}

