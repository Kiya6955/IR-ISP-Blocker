counters() { # prints "tag packets" lines for the live ruleset
    if have nft && nft list table inet "$NFT_TABLE" >/dev/null 2>&1; then
        nft list table inet "$NFT_TABLE" 2>/dev/null | awk '
            /comment "r[0-9]+:/ { match($0, /comment "[^"]+"/); tag=substr($0, RSTART+9, RLENGTH-10)
                                  p=0; if (match($0, /packets [0-9]+/)) p=substr($0, RSTART+8, RLENGTH-8); s[tag]+=p }
            END { for (k in s) print k, s[k] }'
    fi
    local c
    for c in iptables-save ip6tables-save; do
        have "$c" || continue
        { "$c" -c -t filter 2>/dev/null; "$c" -c -t raw 2>/dev/null; } | awk '
            /--comment "?r[0-9]+:/ && !/-j LOG/ { match($0, /--comment "?r[0-9]+:[a-z0-9-]+/); tag=substr($0, RSTART+10, RLENGTH-10); gsub(/"/, "", tag)
                                   match($0, /^\[[0-9]+:/); p=substr($0, 2, RLENGTH-2); s[tag]+=p }
            END { for (k in s) print k, s[k] }'
    done
}

