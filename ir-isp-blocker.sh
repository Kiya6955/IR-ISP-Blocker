# ------------------------------------------------------------------ model building
# Prepares $WORK/model: wl.v4 wl.v6 (whitelist incl. auto SSH clients), sets/<id>.v4/.v6, vars
M_SSH=""; M_WLP=""; M_FWD=0; M_IDS=()
build_model() { # cfgdir
    local dir=$1 id i
    mkwork
    local m="$WORK/model"
    rm -rf -- "$m"; mkdir -p -- "$m/sets"
    local wl
    wl=$(wl_ips_load "$dir")
    if [[ -f $IRB_ETC/state/auto-whitelist ]]; then
        wl+=$'\n'$(cidr_canon any 0 0 0 <"$IRB_ETC/state/auto-whitelist" 2>/dev/null || true)
    fi
    if [[ -n ${M_CLIENT:-} ]]; then wl+=$'\n'$(printf '%s\n' "$M_CLIENT" | cidr_canon any 0 0 0 2>/dev/null || true); fi
    printf '%s\n' "$wl" | awk '$1==4{print $2}' | sort -u | sed '/^$/d' >"$m/wl.v4"
    printf '%s\n' "$wl" | awk '$1==6{print $2}' | sort -u | sed '/^$/d' >"$m/wl.v6"
    M_WLP=$(wl_ports_load "$dir")
    M_SSH=""
    [[ $CFG_SSH_PROTECT == yes ]] && M_SSH=$(detect_ssh_ports)
    M_FWD=0
    detect_docker && M_FWD=1
    M_IDS=()
    local seen=" "
    local ids=()
    for i in "${!R_ID[@]}"; do
        split_csv ids "${R_ISPS[i]}"
        for id in "${ids[@]}"; do
            [[ $seen == *" $id "* ]] && continue
            seen+="$id "; M_IDS+=("$id")
        done
    done
    [[ ${#M_IDS[@]} -gt 0 ]] && ensure_lists "$dir" "${M_IDS[@]}"
    for id in "${M_IDS[@]}"; do
        cidr_canon 4 1 "$MIN_V4_PREFIX" 0 <"$LISTS_DIR/$id.v4" | awk '{print $2}' >"$m/sets/$id.v4" ||
            die "list $id.v4 failed validation"
        if [[ $CFG_IPV6 == yes ]]; then
            cidr_canon 6 1 0 "$MIN_V6_PREFIX" <"$LISTS_DIR/$id.v6" | awk '{print $2}' >"$m/sets/$id.v6" ||
                die "list $id.v6 failed validation"
        else
            : >"$m/sets/$id.v6"
        fi
    done
    return 0
}

# lockout analysis: refuse dangerous configs unless forced
safety_check() { # [soft] - soft: maintenance re-apply of an already accepted config (warn only)
    local i risky=0 soft=${1:-}
    _safety_fail() { if [[ $soft == soft ]]; then warn "$*"; else die "$*"; fi; }
    for i in "${!R_ID[@]}"; do
        if [[ ${R_DIR[i]} != out && ( ${R_PORTS[i]} == all || ${R_MODE[i]} == only ) ]]; then risky=1; fi
    done
    [[ -n $M_SSH ]] && info "$(t ssh_detect "$M_SSH")"
    if [[ $risky -eq 1 && $CFG_SSH_PROTECT == yes && -z $M_SSH ]]; then
        _safety_fail "$(t ssh_none)"
    fi
    if [[ $risky -eq 1 && $CFG_SSH_PROTECT == no ]]; then
        warn "SSH protection is DISABLED and a rule blocks all ports / only-mode inbound traffic."
        [[ $FORCE -eq 1 ]] || _safety_fail "refusing without --force (you could lock yourself out)"
    fi
    for i in "${!R_ID[@]}"; do
        if [[ ${R_RAW[i]} == yes && ${R_PORTS[i]} == all ]]; then
            warn "rule ${R_ID[i]}: raw + all ports also drops replies to this server's own outbound connections to those networks."
        fi
    done
    return 0
}

# ------------------------------------------------------------------ nftables generator
nft_setname() { local s=${1//-/_}; echo "s_${s}_$2"; }

nft_elements() { # file -> "elements = { a, b, ... }" (multi-line) or nothing
    local f=$1
    [[ -s $f ]] || return 0
    printf '    elements = {\n'
    awk '{ printf "%s%s", (NR%6==1 ? "      " : " "), $0; if (NR%6==0) printf ",\n"; else printf "," } END { if (NR%6!=0) printf "\n" }' "$f" |
        sed '$ s/,$//'
    printf '    }\n'
}

nft_set() { # name type file
    printf '  set %s {\n    type %s; flags interval; auto-merge;\n' "$1" "$2"
    nft_elements "$3"
    printf '  }\n'
}

nft_verdict() { # action rule isp
    local tag="r$2:$3"
    case $1 in
        drop)   echo "counter drop comment \"$tag\"" ;;
        reject) echo "counter reject with icmpx type admin-prohibited comment \"$tag\"" ;;
        log)    echo "counter limit rate 10/minute log prefix \"irb $tag: \" level info comment \"$tag\"" ;;
    esac
}

# nft_rule_chain INDEX SIDE(in|out) -> chain body lines
nft_rule_chain() {
    local i=$1 side=$2 rid=${R_ID[$1]} mode=${R_MODE[$1]} action=${R_ACTION[$1]} rate=${R_RATE[$1]}
    local key4="ip saddr" key6="ip6 saddr" id fam ids=()
    [[ $side == out ]] && { key4="ip daddr"; key6="ip6 daddr"; }
    split_csv ids "${R_ISPS[i]}"
    for id in "${ids[@]}"; do
        for fam in 4 6; do
            [[ $fam == 6 && $CFG_IPV6 != yes ]] && continue
            local key=$key4; [[ $fam == 6 ]] && key=$key6
            local set; set=$(nft_setname "$id" "$fam")
            if [[ $mode == only ]]; then
                echo "    $key @$set return"
            elif [[ $action == ratelimit ]]; then
                echo "    $key @$set ct state new update @rl${rid}_$fam { $key limit rate over $rate } counter drop comment \"r$rid:$id\""
            else
                echo "    $key @$set $(nft_verdict "$action" "$rid" "$id")"
            fi
        done
    done
    if [[ $mode == only ]]; then
        local scope="" key
        [[ $CFG_IPV6 != yes ]] && scope="meta nfproto ipv4 "
        if [[ $action == ratelimit ]]; then
            for fam in 4 6; do
                [[ $fam == 6 && $CFG_IPV6 != yes ]] && continue
                key="ip saddr"; [[ $fam == 6 ]] && key="ip6 saddr"
                echo "    meta nfproto ipv$fam ct state new update @rl${rid}_$fam { $key limit rate over $rate } counter drop comment \"r$rid:others\""
            done
        else
            echo "    ${scope}$(nft_verdict "$action" "$rid" others)"
        fi
    fi
}

# match expressions for a rule's ports/proto: prints one match prefix per line
# style: dport (normal) | ctorig (forward, matches pre-DNAT port)
nft_port_matches() { # index style
    local i=$1 style=$2 pspec=${R_PORTS[$1]} proto=${R_PROTO[$1]} p
    if [[ $pspec == all ]]; then
        case $proto in
            any|both) [[ $proto == any ]] && echo "" || echo "meta l4proto { tcp, udp }" ;;
            *) echo "meta l4proto $proto" ;;
        esac
        return 0
    fi
    local protos=(tcp udp)
    [[ $proto == tcp || $proto == udp ]] && protos=("$proto")
    for p in "${protos[@]}"; do
        if [[ $style == ctorig ]]; then echo "meta l4proto $p ct original proto-dst { $(ports_nft "$pspec") }"
        else echo "$p dport { $(ports_nft "$pspec") }"; fi
    done
}

gen_nft() { # -> nft script on stdout
    local m="$WORK/model" i id fam has_in=0 has_out=0 has_raw=0 match
    for i in "${!R_ID[@]}"; do
        if [[ ${R_DIR[i]} != out ]]; then
            if [[ ${R_RAW[i]} == yes ]]; then has_raw=1; else has_in=1; fi
        fi
        [[ ${R_DIR[i]} != in ]] && has_out=1
    done
    echo "# generated by ir-isp-blocker $IRB_VERSION - do not edit; re-run the tool instead"
    echo "table inet $NFT_TABLE"
    echo "delete table inet $NFT_TABLE"
    echo "table inet $NFT_TABLE {"
    nft_set wl_4 ipv4_addr "$m/wl.v4"
    [[ $CFG_IPV6 == yes ]] && nft_set wl_6 ipv6_addr "$m/wl.v6"
    for id in "${M_IDS[@]}"; do
        nft_set "$(nft_setname "$id" 4)" ipv4_addr "$m/sets/$id.v4"
        [[ $CFG_IPV6 == yes ]] && nft_set "$(nft_setname "$id" 6)" ipv6_addr "$m/sets/$id.v6"
    done
    for i in "${!R_ID[@]}"; do
        [[ ${R_ACTION[i]} == ratelimit ]] || continue
        echo "  set rl${R_ID[i]}_4 { type ipv4_addr; size 65536; flags dynamic,timeout; timeout 10m; }"
        [[ $CFG_IPV6 == yes ]] && echo "  set rl${R_ID[i]}_6 { type ipv6_addr; size 65536; flags dynamic,timeout; timeout 10m; }"
    done
    for i in "${!R_ID[@]}"; do
        if [[ ${R_DIR[i]} != out ]]; then
            echo "  chain r${R_ID[i]}_in {"; nft_rule_chain "$i" in; echo "  }"
        fi
        if [[ ${R_DIR[i]} != in ]]; then
            echo "  chain r${R_ID[i]}_out {"; nft_rule_chain "$i" out; echo "  }"
        fi
    done
    # common inbound exemptions
    local wl6="" wlp_lines=()
    [[ $CFG_IPV6 == yes ]] && wl6=1
    if [[ -n $M_WLP ]]; then
        wlp_lines+=("tcp dport { $(ports_nft "$M_WLP") } accept" "udp dport { $(ports_nft "$M_WLP") } accept")
    fi
    if [[ $has_in -eq 1 ]]; then
        echo "  chain input {"
        echo "    type filter hook input priority -10; policy accept;"
        echo "    iif \"lo\" accept"
        echo "    ip saddr @wl_4 accept"
        [[ -n $wl6 ]] && echo "    ip6 saddr @wl_6 accept"
        [[ -n $M_SSH ]] && echo "    tcp dport { $(ports_nft "$M_SSH") } accept comment \"ssh-protect\""
        for match in "${wlp_lines[@]}"; do echo "    $match"; done
        for i in "${!R_ID[@]}"; do
            [[ ${R_DIR[i]} != out && ${R_RAW[i]} != yes ]] || continue
            while IFS= read -r match; do echo "    ct direction original ${match:+$match }jump r${R_ID[i]}_in"; done < <(nft_port_matches "$i" dport)
        done
        echo "  }"
    fi
    if [[ $has_raw -eq 1 ]]; then
        echo "  chain prerouting_raw {"
        echo "    type filter hook prerouting priority -300; policy accept;"
        echo "    iif \"lo\" accept"
        echo "    ip saddr @wl_4 accept"
        [[ -n $wl6 ]] && echo "    ip6 saddr @wl_6 accept"
        [[ -n $M_SSH ]] && echo "    tcp dport { $(ports_nft "$M_SSH") } accept comment \"ssh-protect\""
        for match in "${wlp_lines[@]}"; do echo "    $match"; done
        for i in "${!R_ID[@]}"; do
            [[ ${R_DIR[i]} != out && ${R_RAW[i]} == yes ]] || continue
            while IFS= read -r match; do echo "    ${match:+$match }jump r${R_ID[i]}_in"; done < <(nft_port_matches "$i" dport)
        done
        echo "  }"
    fi
    if [[ $has_out -eq 1 ]]; then
        echo "  chain output {"
        echo "    type filter hook output priority -10; policy accept;"
        echo "    oif \"lo\" accept"
        echo "    ip daddr @wl_4 accept"
        [[ -n $wl6 ]] && echo "    ip6 daddr @wl_6 accept"
        for i in "${!R_ID[@]}"; do
            [[ ${R_DIR[i]} != in ]] || continue
            while IFS= read -r match; do echo "    ct direction original ${match:+$match }jump r${R_ID[i]}_out"; done < <(nft_port_matches "$i" dport)
        done
        echo "  }"
    fi
    if [[ $M_FWD -eq 1 && ( $has_in -eq 1 || $has_out -eq 1 || $has_raw -eq 1 ) ]]; then
        echo "  chain forward {"
        echo "    type filter hook forward priority -10; policy accept;"
        echo "    ip saddr @wl_4 accept"
        echo "    ip daddr @wl_4 accept"
        [[ -n $wl6 ]] && { echo "    ip6 saddr @wl_6 accept"; echo "    ip6 daddr @wl_6 accept"; }
        if [[ -n $M_WLP ]]; then
            echo "    meta l4proto tcp ct original proto-dst { $(ports_nft "$M_WLP") } accept"
            echo "    meta l4proto udp ct original proto-dst { $(ports_nft "$M_WLP") } accept"
        fi
        for i in "${!R_ID[@]}"; do
            if [[ ${R_DIR[i]} != out && ${R_RAW[i]} != yes ]]; then
                while IFS= read -r match; do echo "    ct direction original ${match:+$match }jump r${R_ID[i]}_in"; done < <(nft_port_matches "$i" ctorig)
            fi
            if [[ ${R_DIR[i]} != in ]]; then
                while IFS= read -r match; do echo "    ct direction original ${match:+$match }jump r${R_ID[i]}_out"; done < <(nft_port_matches "$i" ctorig)
            fi
        done
        echo "  }"
    fi
    echo "}"
}

# ------------------------------------------------------------------ iptables / ipset generator
ipt_set() { echo "irb$2-$1"; }   # id fam -> set name (max 31 chars)

# ipt_src_matches FAM ID SIDE -> one match fragment per line (ipset: 1 line; plain: 1 per CIDR)
ipt_src_matches() {
    local fam=$1 id=$2 side=$3 dirflag=src sflag=-s
    [[ $side == out ]] && { dirflag=dst; sflag=-d; }
    if [[ $BACKEND == ipset ]]; then
        echo "-m set --match-set $(ipt_set "$id" "$fam") $dirflag"
    else
        sed "s|^|$sflag |" "$WORK/model/sets/$id.v$fam"
    fi
}

ipt_verdict() { # fam action rid tag -> lines (without "-A CHAIN <match>")
    local fam=$1 action=$2 rid=$3 tag=$4
    case $action in
        drop)   echo "-m comment --comment $tag -j DROP" ;;
        reject) echo "-m comment --comment $tag -j REJECT" ;;
        log)    echo "-m comment --comment $tag"
                echo "-m limit --limit 10/minute -j LOG --log-prefix \"irb $tag: \"" ;;
    esac
}

# ipt_rule_chain FAM INDEX SIDE CHAINNAME
ipt_rule_chain() {
    local fam=$1 i=$2 side=$3 ch=$4 rid=${R_ID[$2]} mode=${R_MODE[$2]} action=${R_ACTION[$2]} rate=${R_RATE[$2]}
    local id v hmode=srcip ids=()
    [[ $side == out ]] && hmode=dstip
    split_csv ids "${R_ISPS[i]}"
    for id in "${ids[@]}"; do
        # verdict fragment(s) are computed once per ISP, then combined with every match
        local frags
        if [[ $mode == only ]]; then
            frags="-j RETURN"
        elif [[ $action == ratelimit ]]; then
            frags="-m conntrack --ctstate NEW -m hashlimit --hashlimit-above $rate --hashlimit-mode $hmode --hashlimit-name irb${fam}r$rid -m comment --comment r$rid:$id -j DROP"
        else
            frags=$(ipt_verdict "$fam" "$action" "$rid" "r$rid:$id")
        fi
        # plain iptables: one line per CIDR x fragment, generated by awk (fast for thousands of CIDRs)
        ipt_src_matches "$fam" "$id" "$side" |
            IRB_FRAGS=$frags awk -v ch="$ch" 'BEGIN { n = split(ENVIRON["IRB_FRAGS"], F, "\n") }
                NF { for (k = 1; k <= n; k++) print "-A " ch " " $0 " " F[k] }'
    done
    if [[ $mode == only ]]; then
        if [[ $action == ratelimit ]]; then
            echo "-A $ch -m conntrack --ctstate NEW -m hashlimit --hashlimit-above $rate --hashlimit-mode srcip --hashlimit-name irb${fam}r$rid -m comment --comment r$rid:others -j DROP"
        else
            while IFS= read -r v; do echo "-A $ch $v"; done < <(ipt_verdict "$fam" "$action" "$rid" "r$rid:others")
        fi
    fi
}

ipt_port_matches() { # index style(dport|ctorig)
    local i=$1 style=$2 pspec=${R_PORTS[$1]} proto=${R_PROTO[$1]} p c item items=()
    local ct=""
    [[ $style == ctorig ]] && ct="-m conntrack --ctdir ORIGINAL"
    if [[ $pspec == all ]]; then
        case $proto in
            any) echo "$ct" ;;
            both) echo "-p tcp${ct:+ $ct}"; echo "-p udp${ct:+ $ct}" ;;
            *) echo "-p $proto${ct:+ $ct}" ;;
        esac
        return 0
    fi
    local protos=(tcp udp)
    [[ $proto == tcp || $proto == udp ]] && protos=("$proto")
    for p in "${protos[@]}"; do
        if [[ $style == ctorig ]]; then
            split_csv items "$pspec"
            for item in "${items[@]}"; do echo "-p $p -m conntrack --ctdir ORIGINAL --ctproto $p --ctorigdstport ${item/-/:}"; done
        else
            while IFS= read -r c; do echo "-p $p -m multiport --dports $c"; done < <(ports_ipt_chunks "$pspec")
        fi
    done
}

IPT_CHAINS_filter=(); IPT_CHAINS_raw=()
gen_ipt() { # fam -> iptables-restore input (filter + raw tables) on stdout
    local fam=$1 m="$WORK/model" i match ch rid wlset c has_raw=0
    local key=-s okey=-d
    wlset=$(ipt_set wl "$fam")
    IPT_CHAINS_filter=(IRB-INPUT IRB-OUTPUT IRB-FORWARD); IPT_CHAINS_raw=(IRB-PREROUTING)
    local body_f="" body_r=""
    for i in "${!R_ID[@]}"; do
        rid=${R_ID[i]}
        if [[ ${R_DIR[i]} != out ]]; then
            if [[ ${R_RAW[i]} == yes ]]; then
                has_raw=1
                IPT_CHAINS_raw+=("IRB-R$rid-IN"); body_r+=$(ipt_rule_chain "$fam" "$i" in "IRB-R$rid-IN")$'\n'
            else
                IPT_CHAINS_filter+=("IRB-R$rid-IN"); body_f+=$(ipt_rule_chain "$fam" "$i" in "IRB-R$rid-IN")$'\n'
            fi
        fi
        if [[ ${R_DIR[i]} != in ]]; then
            IPT_CHAINS_filter+=("IRB-R$rid-OUT"); body_f+=$(ipt_rule_chain "$fam" "$i" out "IRB-R$rid-OUT")$'\n'
        fi
    done
    # whitelist matcher
    local wl_in=() wl_out=()
    if [[ $BACKEND == ipset ]]; then
        wl_in=("-m set --match-set $wlset src"); wl_out=("-m set --match-set $wlset dst")
    else
        while IFS= read -r c; do [[ -n $c ]] && wl_in+=("$key $c") && wl_out+=("$okey $c"); done <"$m/wl.v$fam"
    fi
    echo "*filter"
    for ch in "${IPT_CHAINS_filter[@]}"; do echo ":$ch - [0:0]"; done
    echo "-A IRB-INPUT -i lo -j RETURN"
    for match in "${wl_in[@]}"; do echo "-A IRB-INPUT $match -j RETURN"; done
    if [[ -n $M_SSH ]]; then
        while IFS= read -r c; do echo "-A IRB-INPUT -p tcp -m multiport --dports $c -m comment --comment ssh-protect -j RETURN"; done < <(ports_ipt_chunks "$M_SSH")
    fi
    if [[ -n $M_WLP ]]; then
        while IFS= read -r c; do
            echo "-A IRB-INPUT -p tcp -m multiport --dports $c -j RETURN"
            echo "-A IRB-INPUT -p udp -m multiport --dports $c -j RETURN"
        done < <(ports_ipt_chunks "$M_WLP")
    fi
    for i in "${!R_ID[@]}"; do
        [[ ${R_DIR[i]} != out && ${R_RAW[i]} != yes ]] || continue
        while IFS= read -r match; do echo "-A IRB-INPUT ${match:+$match }-m conntrack --ctdir ORIGINAL -j IRB-R${R_ID[i]}-IN"; done < <(ipt_port_matches "$i" dport)
    done
    echo "-A IRB-OUTPUT -o lo -j RETURN"
    for match in "${wl_out[@]}"; do echo "-A IRB-OUTPUT $match -j RETURN"; done
    for i in "${!R_ID[@]}"; do
        [[ ${R_DIR[i]} != in ]] || continue
        while IFS= read -r match; do echo "-A IRB-OUTPUT ${match:+$match }-m conntrack --ctdir ORIGINAL -j IRB-R${R_ID[i]}-OUT"; done < <(ipt_port_matches "$i" dport)
    done
    if [[ $M_FWD -eq 1 ]]; then
    for match in "${wl_in[@]}" "${wl_out[@]}"; do echo "-A IRB-FORWARD $match -j RETURN"; done
    if [[ -n $M_WLP ]]; then
        local wlitems=()
        split_csv wlitems "$M_WLP"
        for c in "${wlitems[@]}"; do
            echo "-A IRB-FORWARD -p tcp -m conntrack --ctproto tcp --ctorigdstport ${c/-/:} -j RETURN"
            echo "-A IRB-FORWARD -p udp -m conntrack --ctproto udp --ctorigdstport ${c/-/:} -j RETURN"
        done
    fi
    for i in "${!R_ID[@]}"; do
        if [[ ${R_DIR[i]} != out && ${R_RAW[i]} != yes ]]; then
            while IFS= read -r match; do echo "-A IRB-FORWARD $match -j IRB-R${R_ID[i]}-IN"; done < <(ipt_port_matches "$i" ctorig)
        fi
        if [[ ${R_DIR[i]} != in ]]; then
            while IFS= read -r match; do echo "-A IRB-FORWARD $match -j IRB-R${R_ID[i]}-OUT"; done < <(ipt_port_matches "$i" ctorig)
        fi
    done
    fi
    printf '%s' "$body_f"
    echo "COMMIT"
    # the raw table is only touched when a rule needs it (some container kernels lack iptable_raw)
    if [[ $has_raw -eq 0 ]]; then IPT_CHAINS_raw=(); return 0; fi
    echo "*raw"
    for ch in "${IPT_CHAINS_raw[@]}"; do echo ":$ch - [0:0]"; done
    echo "-A IRB-PREROUTING -i lo -j RETURN"
    for match in "${wl_in[@]}"; do echo "-A IRB-PREROUTING $match -j RETURN"; done
    if [[ -n $M_SSH ]]; then
        while IFS= read -r c; do echo "-A IRB-PREROUTING -p tcp -m multiport --dports $c -j RETURN"; done < <(ports_ipt_chunks "$M_SSH")
    fi
    if [[ -n $M_WLP ]]; then
        while IFS= read -r c; do
            echo "-A IRB-PREROUTING -p tcp -m multiport --dports $c -j RETURN"
            echo "-A IRB-PREROUTING -p udp -m multiport --dports $c -j RETURN"
        done < <(ports_ipt_chunks "$M_WLP")
    fi
    for i in "${!R_ID[@]}"; do
        [[ ${R_DIR[i]} != out && ${R_RAW[i]} == yes ]] || continue
        while IFS= read -r match; do echo "-A IRB-PREROUTING ${match:+$match }-j IRB-R${R_ID[i]}-IN"; done < <(ipt_port_matches "$i" dport)
    done
    printf '%s' "$body_r"
    echo "COMMIT"
}

gen_ipset() { # fam -> ipset restore script (create tmp, fill, swap, destroy)
    local fam=$1 m="$WORK/model" id name f family=inet
    [[ $fam == 6 ]] && family=inet6
    for id in wl "${M_IDS[@]}"; do
        name=$(ipt_set "$id" "$fam")
        if [[ $id == wl ]]; then f="$m/wl.v$fam"; else f="$m/sets/$id.v$fam"; fi
        echo "create $name-n hash:net family $family hashsize 1024 maxelem 524288"
        echo "flush $name-n"
        if [[ -s $f ]]; then sed "s|^|add $name-n |" "$f"; fi
        echo "create $name hash:net family $family hashsize 1024 maxelem 524288"
        echo "swap $name-n $name"
        echo "destroy $name-n"
    done
}

# ------------------------------------------------------------------ artifact generation / apply
# gen_all OUTDIR : writes backend artifacts into OUTDIR
gen_all() {
    local out=$1 fam
    mkdir -p -- "$out"
    echo "$BACKEND" >"$out/backend"
    [[ ${#R_ID[@]} -eq 0 ]] && { : >"$out/empty"; return 0; }
    case $BACKEND in
        nft) gen_nft >"$out/ruleset.nft" ;;
        ipset|iptables)
            for fam in 4 6; do
                [[ $fam == 6 && $CFG_IPV6 != yes ]] && continue
                if [[ $fam == 6 && $DRY_RUN -eq 0 && ! -e /proc/net/if_inet6 ]]; then
                    warn "IPv6 is disabled in this kernel: skipping ip6tables rules"; continue
                fi
                [[ $BACKEND == ipset ]] && gen_ipset "$fam" >"$out/ipset$fam.restore"
                gen_ipt "$fam" >"$out/ipt$fam.restore"
                printf '%s\n' "${IPT_CHAINS_filter[@]}" >"$out/chains$fam.filter"
                printf '%s\n' "${IPT_CHAINS_raw[@]}" >"$out/chains$fam.raw"
            done ;;
    esac
}

ipt_cmd() { if [[ $1 == 6 ]]; then echo ip6tables; else echo iptables; fi; }

ipt_has_jump() { # fam table chain target
    "$(ipt_cmd "$1")" -w -t "$2" -C "$3" -j "$4" >/dev/null 2>&1
}
ipt_del_jumps() { # fam table chain target
    local n=0
    while ipt_has_jump "$@" && (( n < 50 )); do
        "$(ipt_cmd "$1")" -w -t "$2" -D "$3" -j "$4" >/dev/null 2>&1 || break
        n=$((n + 1))
    done
}
ipt_chain_exists() { "$(ipt_cmd "$1")" -w -t "$2" -n -L "$3" >/dev/null 2>&1; }

ipt_teardown_fam() { # fam
    local fam=$1 c tbl
    have "$(ipt_cmd "$fam")" || return 0
    ipt_del_jumps "$fam" filter INPUT IRB-INPUT
    ipt_del_jumps "$fam" filter OUTPUT IRB-OUTPUT
    ipt_del_jumps "$fam" filter FORWARD IRB-FORWARD
    ipt_del_jumps "$fam" filter DOCKER-USER IRB-FORWARD
    ipt_del_jumps "$fam" raw PREROUTING IRB-PREROUTING
    for tbl in filter raw; do
        for c in $("$(ipt_cmd "$fam")" -w -t "$tbl" -S 2>/dev/null | awk '$1=="-N" && $2 ~ /^IRB-/ {print $2}'); do
            "$(ipt_cmd "$fam")" -w -t "$tbl" -F "$c" 2>/dev/null || true
        done
        for c in $("$(ipt_cmd "$fam")" -w -t "$tbl" -S 2>/dev/null | awk '$1=="-N" && $2 ~ /^IRB-/ {print $2}'); do
            "$(ipt_cmd "$fam")" -w -t "$tbl" -X "$c" 2>/dev/null || true
        done
    done
}

ipt_teardown_all() { # IRB-* chains (v4+v6) and irb* ipsets
    ipt_teardown_fam 4
    ipt_teardown_fam 6
    if have ipset; then
        local s
        for s in $(ipset list -n 2>/dev/null | grep -E '^irb[46]-' || true); do ipset destroy "$s" 2>/dev/null || true; done
    fi
    return 0
}

teardown_all() { # remove every firewall object we own, any backend
    if have nft && nft list table inet "$NFT_TABLE" >/dev/null 2>&1; then
        run nft delete table inet "$NFT_TABLE"
    fi
    if [[ $DRY_RUN -eq 1 ]]; then echo "+ remove IRB-* iptables/ip6tables chains and irb* ipsets (if any)"; return 0; fi
    ipt_teardown_all
}

apply_ipt_fam() { # fam artifacts-dir
    local fam=$1 a=$2 cmd rcmd tbl c fwd_parent=FORWARD
    cmd=$(ipt_cmd "$fam"); rcmd="$cmd-restore"
    if [[ -f $a/ipset$fam.restore ]]; then
        ipset -exist restore <"$a/ipset$fam.restore" || { err "ipset restore failed (IPv$fam)"; return 1; }
    fi
    local wopt=()
    if "$rcmd" --help 2>&1 | grep -- '--wait' >/dev/null; then wopt=(-w); fi
    "$rcmd" "${wopt[@]}" --test --noflush <"$a/ipt$fam.restore" || { err "$rcmd rejected the generated rules (IPv$fam); nothing changed"; return 1; }
    "$rcmd" "${wopt[@]}" --noflush <"$a/ipt$fam.restore" || { err "$rcmd failed (IPv$fam)"; return 1; }
    ipt_has_jump "$fam" filter INPUT IRB-INPUT || "$cmd" -w -I INPUT 1 -j IRB-INPUT
    ipt_has_jump "$fam" filter OUTPUT IRB-OUTPUT || "$cmd" -w -I OUTPUT 1 -j IRB-OUTPUT
    if grep -q '^\*raw' "$a/ipt$fam.restore"; then
        ipt_has_jump "$fam" raw PREROUTING IRB-PREROUTING || "$cmd" -w -t raw -I PREROUTING 1 -j IRB-PREROUTING
    else
        ipt_del_jumps "$fam" raw PREROUTING IRB-PREROUTING
    fi
    if [[ $M_FWD -eq 1 ]]; then
        if ipt_chain_exists "$fam" filter DOCKER-USER || [[ -S /var/run/docker.sock ]] || have dockerd; then
            ipt_chain_exists "$fam" filter DOCKER-USER || "$cmd" -w -N DOCKER-USER
            fwd_parent=DOCKER-USER
            ipt_del_jumps "$fam" filter FORWARD IRB-FORWARD
        fi
        ipt_has_jump "$fam" filter "$fwd_parent" IRB-FORWARD || "$cmd" -w -I "$fwd_parent" 1 -j IRB-FORWARD
    else
        ipt_del_jumps "$fam" filter FORWARD IRB-FORWARD
        ipt_del_jumps "$fam" filter DOCKER-USER IRB-FORWARD
    fi
    # drop chains that are no longer generated (now unreferenced)
    for tbl in filter raw; do
        for c in $("$cmd" -w -t "$tbl" -S 2>/dev/null | awk '$1=="-N" && $2 ~ /^IRB-/ {print $2}'); do
            grep -qx -- "$c" "$a/chains$fam.$tbl" && continue
            "$cmd" -w -t "$tbl" -F "$c" 2>/dev/null || true
            "$cmd" -w -t "$tbl" -X "$c" 2>/dev/null || true
        done
    done
}

# apply_artifacts DIR : make the kernel state match DIR atomically (per backend)
apply_artifacts() {
    local a=$1 be fam s
    be=$(cat "$a/backend")
    if [[ -f $a/empty ]]; then teardown_all; return 0; fi
    local prev=""
    [[ -f $IRB_ETC/state/applied/backend ]] && prev=$(cat "$IRB_ETC/state/applied/backend")
    case $be in
        nft)
            nft -c -f "$a/ruleset.nft" || { err "nft rejected the generated ruleset; nothing changed"; return 1; }
            nft -f "$a/ruleset.nft" || return 1
            if [[ -n $prev && $prev != nft ]]; then ipt_teardown_all; fi ;;
        ipset|iptables)
            apply_ipt_fam 4 "$a" || return 1
            if [[ -f $a/ipt6.restore ]]; then
                if have ip6tables-restore; then apply_ipt_fam 6 "$a" || return 1
                else warn "ip6tables not available: IPv6 is NOT filtered"; fi
            else
                ipt_teardown_fam 6
            fi
            if have nft && nft list table inet "$NFT_TABLE" >/dev/null 2>&1; then nft delete table inet "$NFT_TABLE"; fi
            if have ipset; then
                local used=" "
                [[ -f $a/ipset4.restore ]] && used+=$(awk '$1=="create" && $2 !~ /-n$/ {printf "%s ", $2}' "$a/ipset4.restore")
                [[ -f $a/ipset6.restore ]] && used+=$(awk '$1=="create" && $2 !~ /-n$/ {printf "%s ", $2}' "$a/ipset6.restore")
                for s in $(ipset list -n 2>/dev/null | grep -E '^irb[46]-' || true); do
                    [[ $used == *" $s "* ]] || ipset destroy "$s" 2>/dev/null || true
                done
            fi ;;
        *) err "unknown backend in artifacts: $be"; return 1 ;;
    esac
    return 0
}

print_artifacts() { # dir
    local a=$1 f
    for f in "$a"/ruleset.nft "$a"/ipset4.restore "$a"/ipt4.restore "$a"/ipset6.restore "$a"/ipt6.restore; do
        [[ -f $f ]] || continue
        printf '%s===== %s =====%s\n' "$C_BLD" "${f##*/}" "$C_RST"
        cat -- "$f"
    done
    [[ -f $a/empty ]] && echo "(no rules: all ir-isp-blocker firewall objects would be removed)"
    return 0
}

