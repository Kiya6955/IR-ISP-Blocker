# parse_ports SPEC -> prints normalized "all" or "a,b,c-d" (sorted, unique); returns 1 if invalid
parse_ports() {
    local spec=${1// /} item a b out=() items=()
    [[ -n $spec ]] || return 1
    if [[ $spec == all || $spec == any || $spec == '*' ]]; then echo all; return 0; fi
    split_csv items "$spec"
    for item in "${items[@]}"; do
        if [[ $item =~ ^([0-9]{1,5})$ ]]; then
            a=$((10#${BASH_REMATCH[1]})); b=$a
        elif [[ $item =~ ^([0-9]{1,5})[-:]([0-9]{1,5})$ ]]; then
            a=$((10#${BASH_REMATCH[1]})); b=$((10#${BASH_REMATCH[2]}))
        else
            return 1
        fi
        (( a >= 1 && b <= 65535 && a <= b )) || return 1
        if (( a == b )); then out+=("$a"); else out+=("$a-$b"); fi
    done
    [[ ${#out[@]} -gt 0 ]] || return 1
    printf '%s\n' "${out[@]}" | sort -t- -k1,1n -k2,2n -u | paste -sd, -
}

ports_nft()  { local s=$1; echo "${s//,/, }"; }
# iptables multiport chunks (max 15 slots, ranges use 2)
ports_ipt_chunks() {
    local spec=$1 item slots=0 cur="" w
    local IFS=,
    for item in $spec; do
        item=${item/-/:}
        if [[ $item == *:* ]]; then w=2; else w=1; fi
        if (( slots + w > 15 )); then echo "$cur"; cur=""; slots=0; fi
        cur=${cur:+$cur,}$item
        slots=$((slots + w))
    done
    [[ -n $cur ]] && echo "$cur"
    return 0
}

# AWK program: validate + canonicalise CIDRs. vars: fam (4|6|any) min4 min6 strict(1|0)
# Output: "4 a.b.c.d/n" or "6 x:x:...:x/n". Strict mode exits 3 on the first bad line.
# shellcheck disable=SC2016  # awk program, $ must not expand
CIDR_AWK='
function hexval(h,  i,v,c){v=0;h=tolower(h);for(i=1;i<=length(h);i++){c=index("0123456789abcdef",substr(h,i,1));if(c==0)return -1;v=v*16+c-1}return v}
function bad(msg){ if(strict){ printf "line %d: %s\n", NR, msg > "/dev/stderr"; exit 3 } }
function p4(s,len,   a,n,i,ip,size,net,o){ n=split(s,a,"."); if(n!=4) return 0
  for(i=1;i<=4;i++){ if(a[i] !~ /^(0|[1-9][0-9]?[0-9]?)$/ || a[i]+0>255) return 0 }
  if(len=="") len=32; if(len !~ /^(0|[1-9][0-9]?)$/ || len+0>32) return 0; len+=0
  if(len<min4) return -1
  ip=a[1]*16777216+a[2]*65536+a[3]*256+a[4]; size=2^(32-len); net=int(ip/size)*size
  o=int(net/16777216)"."int(net/65536)%256"."int(net/256)%256"."net%256
  print "4 " o "/" len; return 1 }
function p6(s,len,   G,L,R,nl,nr,dc,i,k,left,right,b,o,t){
  if(s !~ /^[0-9A-Fa-f:]+$/) return 0
  t=s; dc=gsub(/::/,"::",t); if(dc>1 || s ~ /:::/) return 0
  if(dc==1){ i=index(s,"::"); left=substr(s,1,i-1); right=substr(s,i+2) } else { left=s; right="" }
  nl=(left=="")?0:split(left,L,":"); nr=(right=="")?0:split(right,R,":")
  if(dc==0 && nl!=8) return 0; if(dc==1 && nl+nr>7) return 0
  k=0
  for(i=1;i<=nl;i++){ if(L[i]=="" || length(L[i])>4) return 0; G[++k]=hexval(L[i]) }
  if(dc==1) for(i=0;i<8-nl-nr;i++) G[++k]=0
  for(i=1;i<=nr;i++){ if(R[i]=="" || length(R[i])>4) return 0; G[++k]=hexval(R[i]) }
  if(len=="") len=128; if(len !~ /^(0|[1-9][0-9]?[0-9]?)$/ || len+0>128) return 0; len+=0
  if(len<min6) return -1
  o=""
  for(i=1;i<=8;i++){ b=len-(i-1)*16; if(b<=0) G[i]=0; else if(b<16) G[i]=int(G[i]/2^(16-b))*2^(16-b)
    o=o (i>1?":":"") sprintf("%x",G[i]) }
  if(match(o, /(^|:)0(:0)+(:|$)/)) o=substr(o,1,RSTART-1) "::" substr(o,RSTART+RLENGTH)
  print "6 " o "/" len; return 1 }
{ line=$0; sub(/#.*/,"",line); gsub(/[ \t\r]/,"",line)
  if(line=="") next
  n=split(line,P,"/"); if(n>2){ bad("not a CIDR"); next }
  addr=P[1]; len=(n==2)?P[2]:""
  if(n==2 && len==""){ bad("empty prefix length"); next }
  if(addr ~ /:/){ if(fam=="4"){ bad("IPv6 entry in IPv4 list"); next } r=p6(addr,len) }
  else { if(fam=="6"){ bad("IPv4 entry in IPv6 list"); next } r=p4(addr,len) }
  if(r==0) bad("not a valid IP/CIDR")
  else if(r==-1) bad("prefix too wide (refusing to block that much address space)")
}'

# cidr_canon FAMILY STRICT MIN4 MIN6 < input  -> canonical "fam cidr" lines (sorted, unique)
cidr_canon() {
    local out
    out=$(awk -v fam="$1" -v strict="$2" -v min4="$3" -v min6="$4" "$CIDR_AWK") || return 1
    [[ -n $out ]] && printf '%s\n' "$out" | sort -u
    return 0
}

valid_ip_any() { # single IP or CIDR (whitelist)
    [[ $1 =~ ^[0-9A-Fa-f.:/]+$ ]] || return 1
    [[ -n $(printf '%s\n' "$1" | cidr_canon any 1 0 0 2>/dev/null) ]]
}

parse_duration() { # 90m / 24h / 2d / 3600 -> seconds
    local d=$1
    if [[ $d =~ ^([0-9]+)([smhd]?)$ ]]; then
        local n=$((10#${BASH_REMATCH[1]}))
        case ${BASH_REMATCH[2]} in
            ''|s) echo "$n" ;; m) echo $((n * 60)) ;; h) echo $((n * 3600)) ;; d) echo $((n * 86400)) ;;
        esac
        return 0
    fi
    return 1
}

# ------------------------------------------------------------------ download helpers
fetch() { # fetch URL OUTFILE
    local url=$1 out=$2
    case $url in
        file://*) cp -- "${url#file://}" "$out" ;;
        https://*)
            if have curl; then
                curl -fsSL --proto '=https' --tlsv1.2 --retry 3 --connect-timeout 15 --max-time 180 \
                     --max-filesize 50000000 -o "$out" -- "$url"
            elif have wget; then
                wget -q -T 30 -t 3 -O "$out" -- "$url"
            else
                err "neither curl nor wget is installed"; return 1
            fi ;;
        *) err "refusing non-https URL: $url"; return 1 ;;
    esac
}

sha256_of() {
    if have sha256sum; then sha256sum -- "$1" | awk '{print $1}'
    elif have shasum; then shasum -a 256 -- "$1" | awk '{print $1}'
    elif have openssl; then openssl dgst -sha256 -r -- "$1" | awk '{print $1}'
    else err "no sha256 tool found"; return 1; fi
}

