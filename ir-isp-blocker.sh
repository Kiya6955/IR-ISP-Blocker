}

cmd_whitelist() {
    local sub=${POS[0]:-list} e
    if [[ $sub == list ]]; then
        say "IPs:";   sed 's/^/  /' "$IRB_ETC/whitelist.ips" 2>/dev/null || true
        say "Ports:"; sed 's/^/  /' "$IRB_ETC/whitelist.ports" 2>/dev/null || true
        say "Automatic (recent SSH clients):"; sed 's/^/  /' "$IRB_ETC/state/auto-whitelist" 2>/dev/null || true
        say "SSH ports always exempt: $(cfg_load "$IRB_ETC"; detect_ssh_ports)"
        return 0
    fi
    [[ $sub == add || $sub == remove || $sub == rm || $sub == clear-auto ]] || die "usage: whitelist list|add|remove|clear-auto ENTRY..."
    begin_change
    local s; s=$(stage_new)
    touch "$s/whitelist.ips" "$s/whitelist.ports"
    if [[ $sub == clear-auto ]]; then
        [[ $DRY_RUN -eq 1 ]] || rm -f -- "$IRB_ETC/state/auto-whitelist"
        M_CLIENT=""
    fi
    local entries=()
    split_csv entries "$(IFS=,; echo "${POS[*]:1}")"
    for e in "${entries[@]}"; do
        if [[ $e =~ ^[0-9]+([-:][0-9]+)?$ ]]; then
            local p; p=$(parse_ports "$e") || die "invalid port '$e'"
            if [[ $sub == add ]]; then grep -qxF -- "$p" "$s/whitelist.ports" || echo "$p" >>"$s/whitelist.ports"
            else grep -vxF -- "$p" "$s/whitelist.ports" >"$s/wp.tmp" || true; mv -f -- "$s/wp.tmp" "$s/whitelist.ports"; fi
        else
            valid_ip_any "$e" || die "invalid IP/CIDR '$e'"
            if [[ $sub == add ]]; then grep -qxF -- "$e" "$s/whitelist.ips" || echo "$e" >>"$s/whitelist.ips"
            else grep -vxF -- "$e" "$s/whitelist.ips" >"$s/wi.tmp" || true; mv -f -- "$s/wi.tmp" "$s/whitelist.ips"; fi
        fi
    done
    finish_change "$s" "whitelist $sub"
}

